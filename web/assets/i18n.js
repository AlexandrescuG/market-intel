/* ============================================================================
   SBF I18N — клиентский доступ к тому же словарю, что и сервер (core/i18n.py,
   /api/i18n?lang=). Нужен для sbf-header.js/sbf-profile.js/sbf-feedback.js —
   они не рендерятся через Jinja (строятся строкой в браузере), а серверные
   страницы (index.html/register.html/...) используют {{ t('key', lang) }}
   напрямую и в этом файле не нуждаются.

   Синхронно не выйдет (словарь качается по сети) — window.sbfI18n.ready
   резолвится, когда словарь загружен; для не критичных ко времени вызовов
   (панели, поздние перерисовки) можно просто звать t() сразу — до загрузки
   вернёт ключ как есть, страница не сломается, просто на долю секунды
   пропустит перевод (некритично для навигации/лейблов).
   ========================================================================= */
(function () {
  'use strict';

  function detectLang() {
    // Обычные страницы: /ro/..., /en/... — язык ведущим префиксом пути.
    // Главы курса используют СВОЮ схему /edu/{ro|en}/b/N (сегмент языка
    // ПОСЛЕ /edu/, см. serve.py's _EDU_RE) — без этой ветки shared-шапка
    // (sbf-header.js) на страницах глав всегда качала русский словарь,
    // из-за чего верхний нав ("Сегодня/Обучение/Календарь") оставался
    // русским даже на /edu/ro/b/N и /edu/en/b/N, хотя нижний нав главы
    // (Далее/Назад/Содержание, из _edu_inject на сервере) был переведён.
    var m = location.pathname.match(/^\/(ro|en)(\/|$)/) || location.pathname.match(/^\/edu\/(ro|en)\/b\//);
    return m ? m[1] : 'ru';
  }

  var LANG = detectLang();
  var DICT = {};

  var ready = fetch('/api/i18n?lang=' + LANG)
    .then(function (r) { return r.ok ? r.json() : {}; })
    .then(function (d) { DICT = d || {}; })
    .catch(function () { /* остаёмся на ключах-заглушках, не критично */ });

  function t(key, fallback) {
    return DICT[key] || fallback || key;
  }

  /* 🔴 АДРЕС В ТЕКУЩЕЙ ЛОКАЛИ — ОДНОЙ ФУНКЦИЕЙ, А НЕ КОНКАТЕНАЦИЕЙ НА МЕСТЕ.
     Языковой аудит 17.09 (Л-6): со страницы /ro/ все 77 кликов по
     инструментам вели на «/chart.html» — русский терминал; карточки глав
     на /ro/edu/ — на «/edu/b/N»; «← Acasă» в румынском глоссарии — на «/».
     Ссылка отдавала 200, поэтому ни один щуп «битых ссылок» не срабатывал:
     человек просто проваливался из своего языка в русский и обратно уже
     не возвращался.

     Отдельная тонкость, ради которой это и стоит держать в одном месте:
     у курса локаль идёт ПОСЛЕ /edu (/edu/ro/b/3), у всего остального —
     перед (/ro/brokers). Собирая префикс на месте, об этом забывают —
     так появились 404 на /ro/edu/b (Л-2). */
  function локальныйАдрес(путь) {
    if (!путь || LANG === 'ru') return путь;
    if (!/^\//.test(путь)) return путь;                       // внешняя ссылка
    if (/^\/(ro|en)(\/|$)/.test(путь)) return путь;           // уже локальный
    if (/^\/(assets|data|api)\//.test(путь)) return путь;     // статика и ручки
    if (/^\/edu\/(ro|en)\//.test(путь)) return путь;          // уже локальная глава
    var м = путь.match(/^\/edu\/b(\/.*)?$/);                  // /edu/b и /edu/b/N
    if (м) return '/edu/' + LANG + '/b' + (м[1] || '');
    return '/' + LANG + путь;
  }

  window.sbfI18n = { lang: LANG, t: t, ready: ready, url: локальныйАдрес };
})();
