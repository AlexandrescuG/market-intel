"""channel_agent/news_compose.py — редакторский отбор и написание новостных постов.

ДВЕ СТУПЕНИ, И ЭТО НАМЕРЕННО. Python (news_picker) отвечает на вопрос «что
вообще есть в потоке»: свежесть, важность по посчитанным полям, запрещённые
темы, дубли. Модель отвечает на вопрос «что из этого новость» — и это
редакторское решение, которое числами не выражается.

Почему не только Python: `importance` высоко оценивает и твиттерную риторику
(«They are never going to give you $9,000...», капслок-каша про Иран) — по
формальным признакам это сильный сигнал, по существу не новость. Модель такие
отсеивает, и на прошлых прогонах отказы у неё выходили содержательными.

Почему не только модель: 5241 сигнал в сутки в промпт не влезет, а главное —
фильтр тем и дедупликация должны быть воспроизводимыми, а не зависеть от
настроения генерации.

ФОРМАТ — как в канале (разобран по 3000 постов markettwits): маркер (⚠️
тревожное, ❗️ данные и заявления, ✴️ нейтральное, ⬆️/⬇️ движение), флаги
стран, 2-3 хештега, затем 1-3 предложения. Медиана длины поста там 152 знака.
"""
from __future__ import annotations

import json
import logging

from channel_agent import compose

log = logging.getLogger("channel_agent.news_compose")

PROMPT = """Ты — редактор Telegram-канала SBF «Экономика, Геополитика, Деньги».
Канал русскоязычный, читают его в Молдове.

Тебе дан список кандидатов из нашего собственного потока новостей (RSS, X,
Telegram) за последние часы. Выбери те, что действительно являются НОВОСТЬЮ, и
напиши по каждой пост.

ЧТО БЕРЁМ (это профиль канала, выведенный по его же ленте):
геополитика и войны, санкции, решения центробанков и ставки, макроданные
(инфляция, PMI, занятость), нефть и газ, крипта, отчётность и крупные сделки
компаний, заявления первых лиц с последствиями для рынков.

ЧТО НЕ БЕРЁМ:
- мнения, риторику, треды-рассуждения, «я же говорил» — даже если их много
  репостят;
- текст капслоком без внятного события;
- прогнозы аналитиков вида «X может вырасти» без самого факта;
- пересказ того, что уже было вчера, без нового поворота;
- всё про российские компании и банки, ипотеку, рекламу.

ФОРМАТ ПОСТА (строго):
Первая строка — маркер, флаги стран, хештеги. Примеры:
  «⚠️🇺🇸🇮🇷#иран #санкции #нефть»
  «❗️🇪🇺#дкп #ставка #ецб»
  «✴️#btc #крипто»
Маркеры: ⚠️ — тревожное или эскалация, ❗️ — данные, отчёт, официальное
заявление, ✴️ — нейтральное, ⬆️/⬇️ — заметное движение цены.
Дальше 1-3 предложения по-русски. Коротко: медиана поста в канале — 150 знаков.
Последняя строка — источник:
- если кандидат из X (source = twitter) — «— @автор», автор берётся из поля
  author; «— x.com» писать нельзя, это ничего не говорит читателю;
- если из новостной ленты (source = rss) — «— домен» из url, без www и зоны
  («— reuters», «— cnbc»).

ПРАВИЛА ТЕКСТА:
- ничего не добавляй от себя: только то, что есть в кандидате;
- числа переноси точно, десятичный разделитель — запятая, тысячи — пробелом;
- если у новости несколько источников (publishers > 1), можешь это указать;
- имена и термины по-русски; тикеры латиницей;
- каждое предложение не длиннее 25 слов;
- запрещены слова прогноза и рекомендации: «ожидается», «продолжит»,
  «вырастет», «упадёт», «цель», «прогноз», «покупать», «продавать», «стоит»,
  «рекомендуем», «лонг», «шорт» (проверка идёт по подстроке, словоформы тоже
  нарушают);
- не пиши «по сообщениям СМИ» — источник и так стоит последней строкой.

ОТВЕТ — только JSON, без markdown-обрамления:
{"posts": [{"uid": "<uid кандидата>", "text": "<готовый пост>",
            "image_hint": "<2-4 слова про образ>"}, ...]}
Если ни один кандидат не тянет на новость, верни {"posts": []}.
Выбери не больше %(limit)d кандидатов — лучших.

КАНДИДАТЫ (JSON):
%(candidates)s"""


def _slim(cand: dict) -> dict:
    """Кандидат в том виде, в каком его видит модель: без служебных полей."""
    f = cand["facts"]
    first = (f["sources"] or [{}])[0]
    return {
        "uid": f["uid"],
        "title": f["title"],
        "text": (f["text"] or "")[:600],
        "url": f["url"],
        # source и author нужны модели, чтобы правильно подписать источник:
        # у твита это @автор, у ленты — домен.
        "source": first.get("source"),
        "author": first.get("author"),
        "publishers": f["publishers"],
        "other_sources": [s["author"] for s in f["sources"][1:] if s["author"]][:3],
        "importance": f["importance"],
    }


def write_news(candidates: list[dict], limit: int = 4) -> list[dict]:
    """[{uid, text, image_hint}] — посты, прошедшие валидатор."""
    if not candidates:
        return []
    payload = json.dumps([_slim(c) for c in candidates], ensure_ascii=False, indent=1)
    prompt = PROMPT % {"limit": limit, "candidates": payload}

    raw = compose._run_claude(prompt)
    out = compose._parse(raw or "")
    if not out or not isinstance(out.get("posts"), list):
        log.warning("новостной отбор: ответ модели не разобран")
        return []

    known = {c["facts"]["uid"] for c in candidates}
    good = []
    for post in out["posts"][:limit]:
        uid = (post.get("uid") or "").strip()
        text = (post.get("text") or "").strip()
        if not text:
            continue
        if uid not in known:
            # Модель обязана ссылаться на поданного кандидата. Свободный uid
            # означает, что пост написан не по нашему материалу, — такой
            # публиковать нельзя, проверить его нечем.
            log.warning("новостной отбор: uid %r не из списка кандидатов — пропуск", uid)
            continue
        problems = compose.check(text)
        if problems:
            log.warning("новость %s не прошла проверку: %s", uid, problems)
            continue
        good.append({"uid": uid, "text": text,
                     "image_hint": (post.get("image_hint") or "").strip()})
    return good
