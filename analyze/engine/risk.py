def _corr_now() -> tuple[float, str]:
    """(корреляция, откуда взята). Отдельной функцией, чтобы было видно в тестах."""
    try:
        import json
        d = json.loads(CORR_FILE.read_text(encoding="utf-8"))
        age = (time.time() - float(d["ts"])) / 86400.0
        if age > CORR_MAX_AGE_DAYS:
            return max(CORR_FALLBACK, float(d["p75"])), f"замер протух ({age:.0f} дн)"
        return float(d["p75"]), f"замер от {d['date']}, p75 по {d['pairs']} парам"
    except Exception:                                            # noqa: BLE001
        return CORR_FALLBACK, "замера нет, запасное значение"


def leg_cap(equity_share: float = None) -> float:
    """Потолок на одну ногу, в долях капитала.

    Вывод, а не назначенное число. При попарной корреляции ρ риск N
    одинаковых ставок растёт как sqrt(N + N(N-1)ρ), а не как sqrt(N). Для
    N = MAX_PORTFOLIO_RISK/RISK_PER_TRADE (столько сделок полного размера
    влезает в портфельный потолок) это даёт множитель к тому риску, который
    потолок 3% подразумевает, считая сделки независимыми. На него и делим."""
    rho, _ = _corr_now()
    n = max(1.0, MAX_PORTFOLIO_RISK / RISK_PER_TRADE)
    inflation = ((n + n * (n - 1) * rho) ** 0.5) / (n ** 0.5)
    return (equity_share or MAX_PORTFOLIO_RISK) / inflation

