# 🔴 И честно про цену решения: при 45% риска, съеденных спредом, сделка
# стартует почти с половины пути к стопу. Чтобы газ окупался, его сигналы
# должны быть ЗАМЕТНО лучше монетки — а мы знаем, что наши сигналы монетку не
# бьют. Поэтому газ идёт как отдельный опыт с отдельной кривой, и решение по
# нему принимается по его собственному R, а не по общему счёту.
#
# Правильный выход отсюда — не этот порог, а другая геометрия: на 4h ATR
# больше, и та же доля спреда получается сама собой. Проверить это — задача
# после первых 30 сделок.
# 🔴 07.10 ПУСТО, и пусть таким остаётся. Единственное послабление (NG, 0.45)
# снято вместе с самим инструментом: см. причины у sources.UNIVERSE.
#
# Урок на будущее, он дороже газа. Послабление писалось, чтобы избежать тихой
# деградации — инструмент включён, а каждый сигнал молча отвергается. Лечили
# правильную болезнь неправильным средством: выбор был не «ослабить порог или
# молчать», а «ослабить порог или НЕ ВКЛЮЧАТЬ инструмент». Второе и надо было
# выбрать, потому что порог по издержкам — единственный фильтр, про который у
# нас есть доказательство, что он работает.
#
# Если инструмент проходит только с выключенным фильтром — он не проходит.
SPREAD_RISK_OVERRIDE: dict[str, float] = {}


def spread_limit_for(symbol: str) -> float:
    """Предел доли спреда от риска для инструмента."""
    return SPREAD_RISK_OVERRIDE.get((symbol or "").upper(), MAX_SPREAD_SHARE_OF_RISK)


def cost_gate(signal: Signal, tick) -> None:
    """Спред не должен съедать заметную долю ни награды, ни риска.

    Считается на КАЖДОМ сигнале по живому спреду, а не по списку
    инструментов: спред расширяется ночью и на новостях, и инструмент,
    торгуемый днём, может стать нерентабельным в 3 часа ночи. Статический
    чёрный список этого не поймает."""
    if tick is None:
        return
    spread = abs(float(tick.ask) - float(tick.bid))
    reward = abs(signal.target - signal.ref_price)
    risk = signal.stop_distance
    if reward <= 0 or risk <= 0:
        return
    limit_risk = spread_limit_for(signal.symbol)
    # Порог по награде масштабируется вместе с порогом по риску: у них одна
    # природа, и послабление только в одном месте создало бы дыру во втором.
    limit_reward = MAX_SPREAD_SHARE_OF_TARGET * (limit_risk / MAX_SPREAD_SHARE_OF_RISK)
    share_reward = spread / reward
    if share_reward > limit_reward:
        raise RiskRefusal(
            "spread_too_wide",
            f"спред {spread:.5f} съедает {share_reward * 100:.1f}% награды при пределе "
            f"{limit_reward * 100:.0f}%")
    share_risk = spread / risk
    if share_risk > limit_risk:
        raise RiskRefusal(
            "spread_too_wide",
            f"спред {spread:.5f} — это {share_risk * 100:.1f}% риска при пределе "
            f"{limit_risk * 100:.0f}%: сделка стартует с пути к стопу")


# Запас сверх минимальной дистанции брокера при переносе стопа. Нужен
# потому, что между опросом тика и обработкой запроса цена успевает
# сдвинуться, и стоп, поставленный РОВНО на границу, отбивается. Подробно —
# в докстринге clamp_stop (замер 07.10: на Daoti ни одного переноса).
BARRIER_SAFETY_SHARE = 0.5     # половина сверх требуемого
BARRIER_SAFETY_TICKS = 2.0     # но не меньше двух тиков


def min_barrier(symbol_info, tick) -> float:
    """Минимальная дистанция от цены до стопа, которую примет брокер.

    Одна формула на вход и на сопровождение. Раньше жила только внутри
    broker_barrier_gate, и перенос стопа её не знал — см. clamp_stop."""
    ready = getattr(symbol_info, "stops_level", None)
    if ready is not None:
        need = float(ready)
    else:
        point = float(getattr(symbol_info, "point", 0.0) or 0.0)
        if point <= 0:
            return 0.0
        need = float(getattr(symbol_info, "trade_stops_level", 0) or 0) * point
    if tick is not None:
        need += abs(float(tick.ask) - float(tick.bid))
    return max(0.0, need)


def clamp_stop(new_stop: float, *, is_long: bool, price: float, cur_stop: float,
               symbol_info, tick) -> float | None:
    """Подвинуть стоп настолько, насколько разрешает брокер. None — не двигать.

    🔴 14.09. Сопровождение просило стоп ближе к цене, чем позволяет
    `trade_stops_level`, брокер отвечал `retcode=10016 Invalid stops`, и
    движок пробовал снова КАЖДЫЙ ЧАС с тем же результатом. Замер на живых
    позициях в момент находки:

        USDZAR long   хотели 16.28914 при цене 16.28640 -> 0.00274 при нужных 0.02200
        GBPUSD short  хотели  1.34768 при цене  1.34799 -> 0.00031 при нужных 0.00037
        GBPUSD short  хотели  1.34763 при цене  1.34799 -> 0.00036 при нужных 0.00037

    Постоянный отказ, притворяющийся временным: счётчик ошибок рос, стопы не
    двигались, и сопровождение — ЕДИНСТВЕННОЕ, что у нас измеренно даёт
    преимущество (+0.0765 R на сделку), — молча не работало на этих позициях.

    Не пропускаем перенос, а прижимаем к ближайшему разрешённому уровню:
    запереть меньше прибыли лучше, чем не запереть ничего. Но только вперёд —
    если даже разрешённый уровень хуже нынешнего стопа, не двигаем вовсе.

    🔴 07.10, ДОДЕЛКА. Прижимали РОВНО к границе — `price ± need`. Это и так
    плохо: между опросом тика и обработкой запроса цена двигается, и стоп,
    поставленный точно на границу, оказывается за ней. На Ava это сходило,
    потому что там `trade_stops_level` ненулевой (USDJPY 20 п, USDZAR 120 п)
    и граница заведомо далека от цены; на Daoti он НОЛЬ по всем символам, и
    `need` равна одному спреду — то есть запаса не оставалось вовсе.

    ⚠️ ЧЕСТНО О ПРОИСХОЖДЕНИИ ЭТОЙ ПРАВКИ. Искал я причину отказов
    `retcode=10006` на реальном счёте и сначала решил, что нашёл её здесь.
    Это оказалось НЕ ТАК: отказы шли от того, что у реального счёта с
    30.09 19:54 умер поток котировок, и брокер отбивал любой запрос,
    построенный на недельных ценах. Проверка после правки отказы не убрала.

    Ошибся я и в другом, более опасном: заявил, что на реале «ни одного
    успешного переноса стопа». Смотрел `journalctl`, а он хранит двое суток —
    то есть я измерил окно, в котором всё уже стояло. По журналу базы, где
    запись не стирается, стоп переносился в 57 случаях из 57. Сопровождение
    на реале работало.

    Правка остаётся, потому что запас сверх границы нужен сам по себе. Но
    она НЕ объясняет и не лечит отказы 10006 — их причина на стороне
    брокера. Урок: окно измерения — часть измерения."""
    need = min_barrier(symbol_info, tick)
    point = float(getattr(symbol_info, "point", 0.0) or 0.0)
    # Запас: половина сверх требуемого, но не меньше двух тиков. Половина —
    # чтобы на брокерах с большим stops_level не отодвигать стоп заметно
    # дальше необходимого; два тика — чтобы запас не выродился в ноль там,
    # где сам минимум нулевой.
    need += max(need * BARRIER_SAFETY_SHARE, point * BARRIER_SAFETY_TICKS)
    limit = price - need if is_long else price + need
    allowed = min(new_stop, limit) if is_long else max(new_stop, limit)
    forward = allowed > cur_stop if is_long else allowed < cur_stop
    return allowed if forward else None


def broker_barrier_gate(signal: Signal, symbol_info, tick) -> None:
    """Барьеры должны быть дальше минимума, который требует брокер.

    🔴 Замерено на первом же боевом прогоне 28.08: из 9 принятых сигналов 4
    отбились с `order_check retcode=10016 Invalid stops` — все по USDCNY и
    USDZAR. У брокера `trade_stops_level` в пунктах, и он очень разный:

        GOLD    50 п -> 0.5      EURUSD    1 п -> 0.00001
        USDJPY  20 п -> 0.02     USDCNY   30 п -> 0.003
        USDZAR 120 п -> 0.012    (при спреде ещё 100 п = 0.01)

    Отправлять заведомо отвергаемый ордер плохо не тем, что он не пройдёт, а
    тем, что отказ выглядит как отказ БРОКЕРА, а не как наша негодная
    геометрия. В журнале копились бы `order_rejected` без внятной причины —
    ровно то, от чего уводил комментарий в live_strategy про снос цены.

    Спред добавляется к минимуму осознанно: стоп, стоящий внутри спреда,
    выбьет мгновенно и не по движению рынка."""
    # `stops_level` у MT5 в пунктах, у нашего SymbolInfo — сразу в цене:
    # транспорт приводит к общему виду, чтобы здесь не было развилки.
    ready = getattr(symbol_info, "stops_level", None)
    if ready is not None:
        need_barrier = float(ready)
    else:
        point = float(getattr(symbol_info, "point", 0.0) or 0.0)
        if point <= 0:
            return
        need_barrier = float(getattr(symbol_info, "trade_stops_level", 0) or 0) * point
    spread = 0.0
    if tick is not None:
        spread = abs(float(tick.ask) - float(tick.bid))
    need = need_barrier + spread
    if need <= 0:
        return
    have = signal.stop_distance
    if have < need:
        raise RiskRefusal(
            "barrier_too_close",
            f"стоп {have:.5f} ближе минимума брокера {need:.5f} "
            f"(минимум брокера {need_barrier:.5f} + спред {spread:.5f})")
    tgt = abs(signal.target - signal.ref_price)
    if tgt < need:
        raise RiskRefusal(
            "barrier_too_close",
            f"цель {tgt:.5f} ближе минимума брокера {need:.5f}")


# Доля свободной маржи, которую разрешено занять одной позицией.
# 🔴 Не абстрактная осторожность: на первом боевом прогоне риск-сайзинг дал
# 1.93 лота по USDCNY (пара тихая, поэтому под тот же риск в деньгах
# получается крупный номинал), и order_check показал margin=4283 при
# свободных 9944 — одна сделка забрала бы 43% маржи. Риск в деньгах и
# нагрузка на маржу — разные вещи, ограничивать надо обе.
MAX_MARGIN_SHARE = 0.15


def margin_gate(mt5, broker_sym: str, volume: float, is_buy: bool, price: float,
                free_margin: float) -> None:
    """Занимаемая маржа не больше доли свободной. Считает сам терминал —
    формула зависит от типа инструмента и плеча, и повторять её у себя
    значит однажды разойтись с брокером."""
    try:
        need = mt5.order_calc_margin(
            mt5.ORDER_TYPE_BUY if is_buy else mt5.ORDER_TYPE_SELL,
            broker_sym, volume, price)
    except Exception as e:                                   # noqa: BLE001
        raise RiskRefusal("margin_unknown", f"order_calc_margin упал: {e}") from e
    if need is None:
        raise RiskRefusal("margin_unknown", "order_calc_margin вернул None")
    if free_margin > 0 and float(need) > free_margin * MAX_MARGIN_SHARE:
        raise RiskRefusal(
            "margin_too_big",
            f"нужно маржи {float(need):.2f} при свободных {free_margin:.2f} — "
            f"это больше предела {MAX_MARGIN_SHARE * 100:.0f}%")


def live_risk(direction: str, entry: float | None, stop: float | None,
              risk_per_price: float | None, risk_money: float | None) -> float:
    """Сколько позиция может ещё потерять ПРЯМО СЕЙЧАС, а не сколько могла на входе.

    🔴 14.09. `risk_money` пишется при открытии и больше не меняется, а
    `manage_open` переносит стопы — в безубыток и дальше в прибыль. Позиция с
    выкупленным стопом продолжала занимать полный риск в портфельном лимите.

    Замер на живом счёте в момент находки: шесть открытых сделок занимали
    328.17 USD при потолке 3% ≈ 324 USD, то есть лимит был выбран целиком и
    движок отказывал всем. Реальный остаток риска — 187.51 USD (1.74%): у
    трёх сделок стоп стоял ЗА точкой входа, и терять им было нечего.

    Считается честно в обе стороны: если брокер налил хуже расчётного и
    фактическая дистанция до стопа шире задуманной, живой риск выйдет БОЛЬШЕ
    записанного — так и должно быть.

    За безубытком возвращается 0, а не отрицательное число: запертая прибыль
    — это не «свободный лимит», её нельзя выдать другой сделке."""
    if not risk_per_price or entry is None or stop is None:
        return float(risk_money or 0.0)          # старая строка без пересчёта
    dist = (entry - stop) if direction == "long" else (stop - entry)
    return max(0.0, dist * risk_per_price)


def open_risk_rows(con: sqlite3.Connection, account: str = "demo") -> list[tuple]:
    """Открытые живые позиции ЭТОГО СЧЁТА с уже посчитанным живым риском.

    🔴 Фильтр по счёту обязателен: без него позиции демо занимали бы лимиты
    реального счёта и наоборот, а лимиты — это то немногое, что у нас точно
    работает."""
    rows = con.execute(
        "SELECT symbol, direction, strategy, risk_money, entry_price, stop, "
        "risk_per_price, id FROM engine_trades "
        "WHERE status='open' AND mode='live' AND account=?", (account,)).fetchall()
    return [(r[0], r[1], r[2],
             live_risk(r[1], r[4], r[5], r[6], r[3]), r[7]) for r in rows]


def exposure(rows, add: tuple | None = None) -> tuple[float, float]:
    """(нетто, валовой) риск портфеля в деньгах.

    rows — из open_risk_rows(); add — сделка, которую только собираемся взять,
    в виде (символ, лонг ли, риск).

    Нетто считается ПО ИНСТРУМЕНТАМ и только потом складывается: гасить друг
    друга имеют право лонг и шорт одного EURUSD, а не лонг EURUSD против
    шорта золота. Разные инструменты здесь считаются независимыми — это
    упрощение, и его снимает отдельная работа по валютным ногам (лонг EURUSD,
    лонг GBPUSD и шорт USDJPY — это три раза шорт доллара, а не три
    независимые ставки)."""
    signed: dict[str, float] = {}
    gross = 0.0
    for sym, direction, _strategy, r, _tid in rows:
        r = r or 0.0
        signed[sym] = signed.get(sym, 0.0) + (r if direction == "long" else -r)
        gross += r
    if add:
        sym, is_long, r = add
        signed[sym] = signed.get(sym, 0.0) + (r if is_long else -r)
        gross += r
    return sum(abs(v) for v in signed.values()), gross


def usd_sign(symbol: str) -> int:
    """+1, если рост цены означает сильный доллар; -1 если слабый; 0 если
    доллара в паре нет. Оставлено для отчётов и чек-листа; решения
    принимаются по полному разложению на ноги (см. legs)."""
    try:
        base, quote = legs(symbol)
    except RiskRefusal:
        return 0
    return 1 if base == "USD" else (-1 if quote == "USD" else 0)


# Инструменты, чьё имя не разбирается правилом «шесть букв — две ноги».
#
# 🔴 16.09, найдено сухим прогоном при подключении газа. NG упёрся в отказ
# unknown_legs — предохранитель сработал ровно как задуман: неизвестный
# инструмент отказывает, а не считается нулевым риском. Но газ известен, и
# нога у него есть: он котируется в долларах, как и золото. XAUUSD даёт
# (XAU, USD) по общему правилу, NG — только по этой карте.
LEGS_EXPLICIT = {
    "NG": ("NG", "USD"),        # природный газ, котируется в USD
    "WTI": ("WTI", "USD"),
    "BRENT": ("BRENT", "USD"),
}


def legs(symbol: str) -> tuple[str, str]:
    """Разложение инструмента на базовую и котируемую ногу.

    🔴 14.09, доделка. Первая версия считала ТОЛЬКО доллар и возвращала ноль
    для всего остального — то есть инструмент без доллара в паре молча
    выпадал из расчёта риска целиком. Сегодня это ничего не ломает: все шесть
    торгуемых инструментов — пары с долларом, проверено по журналу сигналов
    за 30 дней. Но это свойство текущего СПИСКА, а не кода: появится EURGBP —
    и он пройдёт мимо всех лимитов, ничего об этом не сказав.

    Поэтому теперь отказ вместо нуля. Неизвестный инструмент — это не
    «нулевой риск», это «риск неизвестен», и вести себя надо наоборот.

    Золото раскладывается как XAU/USD. Это честнее прежнего приёма, где
    XAUUSD считался чистой ставкой на доллар с полным весом: по замеру
    золото — самый слабый член выборки (0.31 с EURUSD, 0.24 с USDJPY), то
    есть в заметной части живёт своей жизнью. Со своей ногой XAU эта часть
    больше никому не приписывается."""
    s = (symbol or "").upper().replace("#", "").replace("/", "")
    if s in LEGS_EXPLICIT:
        return LEGS_EXPLICIT[s]
    if len(s) == 6 and s.isalpha():
        return s[:3], s[3:]
    raise RiskRefusal("unknown_legs",
                      f"{symbol}: не раскладывается на валютные ноги — "
                      f"риск по ногам посчитать нечем")


def leg_exposure(rows, add: tuple | None = None) -> dict[str, float]:
    """Нетто-ставка по каждой ноге, в деньгах со знаком.

    Лонг BASE/QUOTE — это ставка ЗА базовую валюту и ПРОТИВ котируемой,
    поэтому одна позиция даёт вклад в две ноги с разными знаками. Так лонг
    EURUSD и шорт USDJPY складываются в общую ставку против доллара, не
    переставая быть разными ставками по евро и иене."""
    e: dict[str, float] = {}
    def put(sym: str, signed: float) -> None:
        base, quote = legs(sym)
        e[base] = e.get(base, 0.0) + signed
        e[quote] = e.get(quote, 0.0) - signed
    for sym, direction, _strategy, r, _tid in rows:
        put(sym, (r or 0.0) * (1 if direction == "long" else -1))
    if add:
        sym, is_long, r = add
        put(sym, r * (1 if is_long else -1))
    return e


def usd_exposure(rows, add: tuple | None = None) -> float:
    """Долларовая нога по модулю — короткий доступ для отчётов."""
    return abs(leg_exposure(rows, add).get("USD", 0.0))


def crossing_trade(con: sqlite3.Connection, symbol: str, is_long: bool,
                   account: str = "demo") -> int | None:
    """id открытой ВСТРЕЧНОЙ позиции по тому же инструменту, если она есть.

    Раньше здесь стоял запрет (`opposite_open`): встречный вход отклонялся,
    чтобы не путать измерение. 627 отклонённых сигналов за 14 дней —
    четвёртая по величине причина отказа, и единственная, которая не
    защищала счёт.

    🔴 Обоснование запрета к тому же не выдержало проверки. В докстринге
    было написано, что встречная позиция гасит часть движения и «R перестаёт
    значить то, что написано». Но R считается в ledger.close_trade по ЦЕНАМ
    самой сделки — её вход, её стоп, её выход, — и чужая позиция в эту
    арифметику не входит вовсе. Портилось не R, а подсчёт портфельного
    риска, и это чинится подсчётом, а не запретом.

    Вместо запрета — пометка: сделка запоминает, с чем она пересеклась, и
    выборку можно разделить задним числом."""
    row = con.execute(
        "SELECT id FROM engine_trades WHERE status='open' AND mode='live' "
        "AND account=? AND symbol=? AND direction=? ORDER BY id DESC LIMIT 1",
        (account, symbol, "short" if is_long else "long")).fetchone()
    return int(row[0]) if row else None


def portfolio_gate(con: sqlite3.Connection, signal: Signal, equity: float,
                   risk_money: float, account: str = "demo") -> None:
    """Лимиты кучности и суммарного риска.

    🔴 Причина существования — 26-27.08: старый потолок «10 наших позиций»
    не различал символ и направление, набралось десять лонгов по золоту, и
    развернувшийся рынок вынес их одним движением (шесть стопов за 13 минут,
    три за одну минуту). Десять одинаковых ставок — это одна ставка размером
    в десять, и потолок обязан это понимать."""
    rows = open_risk_rows(con, account)
    total = len(rows)
    if total >= MAX_OPEN_TOTAL:
        raise RiskRefusal("cap_total", f"открыто {total} при потолке {MAX_OPEN_TOTAL}")

    same_symbol = [r for r in rows if r[0] == signal.symbol]
    if len(same_symbol) >= MAX_OPEN_PER_SYMBOL:
        raise RiskRefusal("cap_symbol",
                          f"по {signal.symbol} открыто {len(same_symbol)} при потолке "
                          f"{MAX_OPEN_PER_SYMBOL}")

    same_strat = [r for r in rows if r[2] == signal.strategy]
    if len(same_strat) >= MAX_OPEN_PER_STRATEGY:
        raise RiskRefusal("cap_strategy",
                          f"у стратегии {signal.strategy} открыто {len(same_strat)} "
                          f"при потолке {MAX_OPEN_PER_STRATEGY}")

    strat_net, _ = exposure(same_strat,
                            add=(signal.symbol, signal.is_long, risk_money))
    if equity > 0 and strat_net / equity > MAX_STRATEGY_RISK:
        raise RiskRefusal(
            "cap_strategy_risk",
            f"риск стратегии {signal.strategy} {strat_net / equity * 100:.2f}% "
            f"превысит предел {MAX_STRATEGY_RISK * 100:.1f}%")

    if equity <= 0:
        return

    # Потолок на инструмент — в деньгах, а не в штуках.
    #
    # 🔴 14.09. Раньше здесь стояло «не больше двух в одну сторону» —
    # 416 отказов за 14 дней, 207 из них по EURUSD. Штуки не различают
    # позицию с полным риском и позицию с выкупленным стопом: третий вход
    # блокировался, даже когда двум предыдущим уже нечего было терять.
    #
    # Урок 26-27.08 при этом сохраняется и даже усиливается: десять лонгов
    # по золоту упрутся в потолок на третьем (0.5% на сделку против 1.5% на
    # инструмент), а не на десятом.
    sym_rows = [r for r in rows if r[0] == signal.symbol]
    sym_net, _ = exposure(sym_rows, add=(signal.symbol, signal.is_long, risk_money))
    if sym_net / equity > MAX_SYMBOL_RISK:
        raise RiskRefusal(
            "cap_symbol_risk",
            f"направленный риск по {signal.symbol} {sym_net / equity * 100:.2f}% "
            f"превысит предел {MAX_SYMBOL_RISK * 100:.2f}%")

    net, gross = exposure(rows, add=(signal.symbol, signal.is_long, risk_money))
    if net / equity > MAX_PORTFOLIO_RISK:
        raise RiskRefusal(
            "cap_portfolio_risk",
            f"направленный риск {net / equity * 100:.2f}% превысит предел "
            f"{MAX_PORTFOLIO_RISK * 100:.2f}%")
    if gross / equity > MAX_GROSS_RISK:
        raise RiskRefusal(
            "cap_gross_risk",
            f"валовой риск {gross / equity * 100:.2f}% превысит предел "
            f"{MAX_GROSS_RISK * 100:.2f}% (пила выбивает встречные стопы оба)")

    # Общий множитель: сколько бы инструментов ни было, ставка может
    # оказаться одна. Считается по ВСЕМ ногам, а не только по доллару —
    # иначе первая же пара без доллара пройдёт мимо лимита молча.
    cap = leg_cap()
    legs_now = leg_exposure(rows, add=(signal.symbol, signal.is_long, risk_money))
    for cur, e in sorted(legs_now.items(), key=lambda kv: -abs(kv[1])):
        if abs(e) / equity > cap:
            rho, src = _corr_now()
            raise RiskRefusal(
                "cap_leg_risk",
                f"ставка по {cur} {abs(e) / equity * 100:.2f}% превысит предел "
                f"{cap * 100:.2f}% (инструменты разные, нога одна; "
                f"корреляция {rho:.2f} — {src})")


