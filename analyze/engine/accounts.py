#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
analyze/engine/accounts.py — профили торговых счетов.

Один источник правды о том, чем счета отличаются друг от друга. До 16.09
счёт был один и его свойства лежали константами по всему движку; с приходом
реального счёта Daoti их стало два, и разница между ними обязана быть
перечислимой, а не размазанной.

ЧТО РАЗНОЕ У СЧЕТОВ
  · свой терминал в своей бутылке Wine, свой rpyc-порт;
  · своя файловая блокировка моста — иначе клиенты одного счёта встанут в
    очередь за клиентами другого без всякой причины;
  · своя доля риска на сделку (капитал разный, доля тоже может отличаться);
  · свой набор инструментов.

ЧТО ОБЩЕЕ И ПОЧЕМУ
  Портфельные потолки (нетто, валовой, нога, инструмент, стратегия) заданы
  В ДОЛЯХ КАПИТАЛА и от размера счёта не зависят. Разводить их по счетам
  значило бы менять условия эксперимента, а смысл второго счёта именно в
  том, чтобы сравнивать одинаковые правила на разном капитале.

🔴 ЗОЛОТА НА РЕАЛЬНОМ СЧЁТЕ НЕТ, И ЭТО НЕ НАСТРОЙКА.
Минимальный лот GOLD при стопе 1.5 ATR стоит 22.10 USD. При 1% от 1400 это
14.00 — движок откажет с `risk_too_small` на каждом сигнале. Нижний предел
риска задаёт брокер, а не мы. Поэтому XAUUSD исключён из набора явно: лучше
не просить, чем просить и получать отказ, неотличимый от «сигналов нет».
"""
from __future__ import annotations

from dataclasses import dataclass

DEMO = "demo"
REAL = "real"


@dataclass(frozen=True)
class Account:
    name: str
    port: int                      # rpyc-порт своего моста
    lock: str                      # своя файловая блокировка
    risk_per_trade: float
    symbols: tuple[str, ...]
    note: str
    # Номер счёта. Для реального профиля это предохранитель: движок откажется
    # торговать, пока номер не заполнен и пока мост показывает другой счёт
    # (см. execution.preflight_account). Заполняется ПОСЛЕ того, как владелец
    # авторизовался в терминале и номер увиден живьём, а не переписан из
    # письма.
    login: int | None = None

    @property
    def is_real(self) -> bool:
        return self.name == REAL


ACCOUNTS: dict[str, Account] = {
    DEMO: Account(
        name=DEMO,
        port=18812,
        lock="/tmp/sbf-mt5-bridge.lock",         # historический путь, не менять:
                                                 # на него уже ссылаются другие клиенты
        risk_per_trade=0.005,
        symbols=("XAUUSD", "EURUSD", "GBPUSD", "USDJPY", "USDCNY", "USDZAR", "NG"),
        note="Ava-Demo 1-MT5, счёт 101746781 — площадка для опытов",
        login=101746781,
    ),
    REAL: Account(
        name=REAL,
        port=18813,
        lock="/tmp/sbf-mt5-bridge-real.lock",
        risk_per_trade=0.01,                     # решение владельца 16.09: 1% от 1400
        # Газа здесь пока нет СОЗНАТЕЛЬНО: его подключают на демо, и он
        # попадёт сюда, когда отработает по собственной кривой R.
        # XAUUSD нет по причине выше — не влезает в минимальный лот.
        symbols=("EURUSD", "GBPUSD", "USDJPY", "USDCNY", "USDZAR"),
        note="Daoti, 1400 USD от партнёра — продолжение эксперимента на живых деньгах",
    ),
}


def get(name: str) -> Account:
    if name not in ACCOUNTS:
        raise SystemExit(f"нет профиля счёта {name!r}; есть: {sorted(ACCOUNTS)}")
    return ACCOUNTS[name]
