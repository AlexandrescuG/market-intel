#!/usr/bin/env bash
# Дневной пайплайн (cron 06:00): бриф → анализ Claude Code → отчёт в Telegram.
set -euo pipefail
cd "$(dirname "$0")/.."
export PYTHONPATH="$PWD"

# Обеспечиваем PATH для cron/systemd: claude живёт в ~/.local/bin
export PATH="$HOME/.local/bin:$PATH"

# Загрузка .env (TELEGRAM_BOT_TOKEN и др.)
[ -f .env ] && set -a && source .env && set +a || true

# venv если есть
[ -f .venv/bin/activate ] && source .venv/bin/activate || true

TODAY="$(date +%F)"
BRIEF="data/briefs/brief_${TODAY}.md"
REPORT="data/reports/report_${TODAY}.md"
CONTEXT_FILE="data/reports/context_${TODAY}.json"
FOCUS_ANALYSIS_PATTERN="data/focus/analysis_${TODAY}_<ТИКЕР>.txt"

echo "[$(date +%T)] 0/3 Focus Engine (ATR-кэш + фокус дня)…"
mkdir -p data/focus
# Некритично для основного отчёта -- если движок упал, build_brief.py сам
# обнаружит отсутствие focus_state и молча пропустит блок «В ФОКУСЕ» (см.
# try/except там же). Также подстрахован таймером sbf-focus-batch.timer в
# 05:50 -- запуск дважды за 10 мин безвреден (INSERT OR REPLACE везде).
python3 focus_batch_job.py --verbose || echo "focus_batch_job упал, продолжаем без блока фокуса"

echo "[$(date +%T)] 1/3 сборка брифа…"
python3 -m analyze.build_brief --hours 24

echo "[$(date +%T)] 2/3 анализ через Claude Code…"
# claude -p headless: читает бриф, пишет отчёт. allowedTools — без интерактивных запросов.
claude -p "$(cat analyze/prompt.md)

ИСХОДНЫЙ БРИФ лежит в файле: ${BRIEF}
Сегодняшняя дата и время (локальное): $(date '+%Y-%m-%d %H:%M %Z').
Прочитай бриф (Read) и запиши готовый отчёт в файл: ${REPORT} (Write).
Файл для ГЛАВНОЙ ЗАДАЧИ (headline+context, см. инструкции выше) запиши по
пути: ${CONTEXT_FILE} (Write).
Сверяй заявления из соцсетей с блоком РЕАЛЬНОЕ СОСТОЯНИЕ РЫНКА.
События, уже прошедшие к этой дате/времени, разбирай по факту, а не как прогноз.
Если в брифе есть блок «В ФОКУСЕ СЕГОДНЯ» — см. раздел «ДОПОЛНИТЕЛЬНО — ФОКУС
ДНЯ» выше в инструкциях. Там может быть НЕСКОЛЬКО инструментов списком — для
КАЖДОГО запиши отдельный файл по шаблону пути: ${FOCUS_ANALYSIS_PATTERN}
(замени <ТИКЕР> на тикер этого инструмента из скобок в брифе, Write).
Если блока «В ФОКУСЕ СЕГОДНЯ» в брифе нет — файлы фокуса не создавай.
Верни в stdout только путь к отчёту." \
  --allowedTools "Read" "Write" \
  --output-format text \
  || LLM_FAILED=1

# 🔴 29.09.2026: отказ модели БОЛЬШЕ НЕ РОНЯЕТ пайплайн. Раньше здесь стоял
# `exit 1`, и 17-29 сентября брифинг не собирался вовсе: у организации
# отключили доступ к Claude Code («Your organization has disabled Claude
# subscription access»). Двенадцать дней подписчики не получали ничего —
# хотя числа, календарь, выбросы и картинка модели не требуют и считаются
# обычным Python'ом.
#
# Аналитическая часть — это ОДИН блок брифинга из пяти. Когда модель
# недоступна, дальше идёт деградированный прогон: бот сам увидит, что
# headline/context не смержены, и отрисует сокращённый вид (render.py).
if [ "${LLM_FAILED:-0}" = 1 ] || [ ! -s "$REPORT" ]; then
  # ЗАПАСНОЙ ПУТЬ 1: тот же claude, но по API-ключу вместо подписки. Именно
  # это предлагает само сообщение об отказе («Use an Anthropic API key
  # instead»), и именно этот путь переживает отключение подписки для Claude
  # Code. Ключ берём из .env; пока он пуст, ветка просто пропускается.
  if [ -n "${ANTHROPIC_API_KEY:-}" ]; then
    echo "[$(date +%T)] 2·запас: повтор через ANTHROPIC_API_KEY…"
    ANTHROPIC_API_KEY="$ANTHROPIC_API_KEY" claude -p "$(cat analyze/prompt.md)

ИСХОДНЫЙ БРИФ лежит в файле: ${BRIEF}
Сегодняшняя дата и время (локальное): $(date '+%Y-%m-%d %H:%M %Z').
Прочитай бриф (Read) и запиши готовый отчёт в файл: ${REPORT} (Write).
Файл для ГЛАВНОЙ ЗАДАЧИ (headline+context) запиши по пути: ${CONTEXT_FILE} (Write).
Файлы фокуса не создавай.
Верни в stdout только путь к отчёту." \
      --allowedTools "Read" "Write" --output-format text \
      && [ -s "$REPORT" ] && LLM_FAILED=0 && echo "[$(date +%T)] аналитика собрана по API-ключу"
  fi
fi

if [ "${LLM_FAILED:-0}" = 1 ]; then
  # ЗАПАСНОЙ ПУТЬ 2 (по умолчанию ВЫКЛЮЧЕН): локальная модель в Ollama.
  # Оплаты не требует, но замерен дважды и оба раза не годится:
  #
  # 29.09 — качество. qwen2.5-coder:7b пишет бессмыслицу («Золото
  # подорвало уровень $4200», «Индекс Мосбиржи показывает дайджест
  # Хэдхантера»), sbf-reasoner 27B не уложилась и в десять минут.
  #
  # 30.09 — скорость. Bonsai 2 27B (тернарная, 98,2% качества FP16 —
  # то есть по качеству вопрос снят) на этом процессоре выдала 0.15
  # токена в секунду: один брифинг занял бы от четырёх до девяти часов.
  # Мерили на двух носителях: с жёсткого диска 0.13, с SSD 0.15 —
  # упирается в арифметику CPU, а не в чтение файла. Подробности и все
  # цифры — ops/bonsai_setup.sh.
  #
  # Вывод: на этом железе локальная модель либо врёт, либо не успевает.
  # Настоящий резерв — ANTHROPIC_API_KEY выше. Искажённый текст в
  # рассылке хуже отсутствующего, поэтому путь включается осознанно:
  # BRIEF_LOCAL_LLM=1 и модель в BRIEF_LOCAL_MODEL.
  if [ "${BRIEF_LOCAL_LLM:-0}" = 1 ]; then
    echo "[$(date +%T)] 2·запас: локальная модель…"
    # 🔴 Успех тут — это НАПИСАННЫЙ ФАЙЛ, а не нулевой код возврата.
    # Соседний запасной путь (по API-ключу) проверяет `[ -s "$REPORT" ]`,
    # а этот верил коду — и в прогоне 29.09 объявил «аналитика собрана
    # локальной моделью», когда контекста не было вовсе. Дальше это
    # снимало LLM_FAILED, а значит не звало notify_degraded и оставляло
    # нулевой код выхода: половинчатый прогон выглядел бы успехом и в
    # systemd, и в надзоре. Ровно тот класс отказа («exit 0 при отказе»),
    # ради которого вся эта цепочка и написана.
    if python3 -m analyze.llm_context_local --date "$TODAY" \
         --model "${BRIEF_LOCAL_MODEL:-qwen2.5-coder:7b}" \
       && [ -s "$CONTEXT_FILE" ]; then
      LLM_FAILED=0; LLM_LOCAL=1
      echo "[$(date +%T)] аналитика собрана локальной моделью"
    else
      echo "[$(date +%T)] локальная модель не дала контекста — путь не засчитан"
    fi
  fi
fi

if [ "${LLM_FAILED:-0}" = 1 ]; then
  echo "[$(date +%T)] ⚠️ аналитическая часть НЕ собрана — продолжаем без неё"
  python3 -m analyze.notify_degraded --reason "claude -p недоступен, запасные пути не дали текста" || true
else
  # Авария кончилась — сказать об этом один раз. Молчит, если её не было.
  python3 -m analyze.notify_degraded --recovered || true
fi

echo "[$(date +%T)] 2a/3 проверка headline/context валидатором Telegram-пуша…"
# Проверять нечего, если модель не отработала: recheck_context позвал бы её
# снова и снова упёрся бы в тот же отказ.
# 31.08.2026. Правила текста живут у бота (SBFAcademy_bot/.../validate.py), а
# пишет текст модель здесь -- и обратной связи между ними не было: пункт на 26
# слов при лимите 25 стоил подписчику всей аналитической части поста, молча.
# Теперь нарушения возвращаются модели дословно, с процитированной фразой, и
# она переписывает файл. Строго ДО llm_context.py: тот мерджит context в
# brief_today.json, после мерджа править уже поздно.
# `|| true` намеренно: провал переделки -- не повод ронять утренний пайплайн,
# бот отбракует нарушающие пункты поштучно и опубликует остальное.
# При локальной модели переделку не зовём: recheck_context чинит текст через
# claude -p, а он в этой ветке как раз и недоступен. Нарушения отбракует бот.
[ "${LLM_FAILED:-0}" = 1 ] || [ "${LLM_LOCAL:-0}" = 1 ] \
  || python3 -m analyze.recheck_context --date "$TODAY" || true

echo "[$(date +%T)] 2b/3 деривация brief_today.json (SPEC_morning_brief_v2.md,
  раньше запускалась только вручную -- см. docs/BRIEF_V2_PROGRESS.md)…"
# Некритично для отчёта/Telegram-дайджеста выше -- build_brief_v2.py и
# llm_context.py пишут ОТДЕЛЬНЫЙ файл (web/data/brief_today.json), который
# report.json/Telegram-отправка ниже не читают. Порядок важен: build_brief_v2
# перезаписывает brief_today.json целиком, llm_context.py домердживает
# headline/context ПОВЕРХ него -- в обратном порядке правки потерялись бы.
# SPEC_brief_outliers §3.2: спросить модель, что из тем дня — событие. Строго
# ДО build_brief_v2: он читает уже проставленные summary_status='ok', и в
# обратном порядке блок «Выбивается из контекста» собрался бы по вчерашним
# темам. Скан выбросов (sbf-outliers.timer, раз в 15 мин) триаж не делает —
# 96 вызовов модели в сутки ради одного блока это цена без содержания.
# Триаж тоже ходит к модели — при её отказе просто пропускаем блок.
[ "${LLM_FAILED:-0}" = 1 ] \
  || python3 outliers_job.py --triage \
  || echo "триаж выбросов не отработал, блок «вне контекста» будет пуст"

python3 -m analyze.build_brief_v2 || echo "build_brief_v2 упал, brief_today.json не обновлён"
python3 -m analyze.llm_context || echo "llm_context упал, headline/context не смержены"

# SPEC_brief_outliers §4.2/§5: картинка (котировки + 4 часовых графика) по уже
# собранному брифу. Строго ПОСЛЕ него — рисуется по тем же числам, что и текст,
# иначе картинка и текст разойдутся в первый же день. Падение здесь не трогает
# ни отчёт, ни текстовый брифинг: бот шлёт фото отдельным сообщением и,
# не найдя файла, просто его не шлёт.
python3 brief_image_job.py || echo "картинка брифинга не отрисована, уйдёт только текст"

echo "[$(date +%T)] 3/3 отправка в Telegram + публикация на сайт…"
# Отчёт — продукт модели; без неё файла нет, и слать нечего. Остальное
# (brief_today.json для бота, картинка, дашборд) уже собрано выше и уходит.
if [ -s "$REPORT" ]; then
  python3 -m core.telegram --send-file "$REPORT"
else
  echo "отчёта нет — Telegram-дайджест пропущен, данные брифинга обновлены"
fi
# обновить report.json, чтобы дашборд показал свежий отчёт
PYTHONPATH="$PWD" python3 publish.py >/dev/null 2>&1 || true

if [ "${LLM_FAILED:-0}" = 1 ]; then
  echo "[$(date +%T)] готово ЧАСТИЧНО: данные обновлены, аналитики нет"
  # Ненулевой код: «сработало наполовину» не должно выглядеть как успех в
  # systemd и в healthcheck. Но это 1, а не падение на середине пути.
  exit 1
fi
echo "[$(date +%T)] готово: $REPORT"
