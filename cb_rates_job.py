#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""cb_rates_job.py — ставки трёх центробанков для станции «Сегодня» главы 2.

🔴 ЗАЧЕМ. Станция «Сегодня» показывала «ФРС 3.63% ↓ · пик цикла 5.25-5.50%
(2023) · 21.07.2026», «ЕЦБ 2.25% ↑», «BoJ 1.00% ↑ · макс. с 1995 ·
16.06.2026» — и все три числа были вбиты строковыми литералами прямо в
SVG. Комментарий над кодом при этом утверждал: «Реальные значения из
web/data/edu_capsules/cb_rates_now.json (обновлено 23.07.2026)». Файла с
таким именем не существовало нигде в проекте — единственное упоминание во
всём дереве было в самом этом комментарии.

Важно, чем именно это плохо. Числа были ВЕРНЫ на день, когда их вписали, —
это не выдумка. Плохо другое: они не могли перестать быть верными
заметно. 17-18 сентября 2026 у Банка Японии заседание, ставку ждут 1.25%;
после него станция продолжила бы показывать 1.00% с подписью «Federal
Reserve H.15 · ECB · Bank of Japan» и уверенной датой — и ни один тест,
ни одна проверка не сказали бы ни слова. Ровно тот класс, что уже ловили
на этом проекте: молчаливая деградация, где «работает» и «право» разошлись.

🔴 ДАТА И СТРЕЛКА СЧИТАЮТСЯ, А НЕ ВПИСЫВАЮТСЯ. Направление (↑/↓) и дата
последнего шага берутся из самого ряда: ищем последний день, когда
значение отличается от предыдущего. Вписанная руками дата — это ещё одно
число, которое может разойтись с действительностью; вычисленная разойтись
не может.

ИСТОЧНИКИ (все через FRED, один ключ, уже настроенный в .env):
  DFEDTARU / DFEDTARL — целевой диапазон ФРС, ежедневно.
  ECBDFR              — ставка по депозитам ЕЦБ, ежедневно. Именно она с
                        2019 года направляет денежный рынок еврозоны;
                        MRO (ECBMRRFR) берём справочно.
  IRSTCI01JPM156N     — фактическая необеспеченная ставка овернайт Японии,
                        ЕЖЕМЕСЯЧНАЯ средняя. Целевой ставки Банка Японии в
                        FRED нет, и подменять одно другим молча нельзя:
                        в JSON у японской записи стоит признак
                        «это_факт_а_не_цель», станция обязана его показать.

Запуск:  python3 cb_rates_job.py [--verbose]
Частота: раз в сутки. Чаще бессмысленно — ряды дневные.
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(КОРЕНЬ))
from core.fred import series  # noqa: E402

log = logging.getLogger("cb_rates")
ВЫХОД = КОРЕНЬ / "web" / "data" / "edu_capsules" / "cb_rates_now.json"

# Сколько наблюдений тянуть, чтобы поймать последнее изменение. Ставки
# меняются несколько раз в год; 1200 дневных значений — это больше трёх
# лет, хватает даже для ЕЦБ, стоявшего на месте с 2019 по 2022.
ГЛУБИНА_ДНЕВНАЯ = 1200
ГЛУБИНА_МЕСЯЧНАЯ = 60


def по_убыванию(ряд: list[dict]) -> list[dict]:
    """Свежее наблюдение — первым, каким бы порядком ряд ни пришёл.

    🔴 НЕ ДОВЕРЯТЬ ПОРЯДКУ НА СЛОВО. core.fred.series() просит у FRED
    sort_order=desc и затем разворачивает ответ — то есть отдаёт по
    ВОЗРАСТАНИЮ, вопреки тому, что можно предположить по параметру
    запроса. Первый прогон на этом и попался: при глубине 1200 дней
    ряд[0] оказался 3 июня 2023 года, и файл уверенно сообщил «ФРС
    5.00–5.25%, ЕЦБ 3.25%, Банк Японии −0.04%» — данные трёхлетней
    давности с сегодняшней отметкой времени. На глубине 2 ошибка не
    видна вовсе: два соседних дня почти всегда равны. Поэтому порядок
    здесь не предполагается, а задаётся.
    """
    return sorted(ряд, key=lambda о: о["date"], reverse=True)


def последнее_изменение(ряд: list[dict]) -> tuple[str | None, float | None]:
    """Дата, когда значение в последний раз стало другим, и прежний уровень.

    Ряд отсортирован по убыванию. Идём от свежего к старому и ищем первое
    несовпадение с текущим значением: это и есть день шага.
    """
    if not ряд:
        return None, None
    текущее = ряд[0]["value"]
    for i, о in enumerate(ряд):
        if о["value"] != текущее:
            # Предыдущее наблюдение — первый день нового уровня.
            return ряд[i - 1]["date"], о["value"]
    return None, None


def запись(имя: str, значение: float, ряд: list[dict], **ещё) -> dict:
    дата, прежнее = последнее_изменение(ряд)
    if прежнее is None:
        направление = "="
    else:
        направление = "↑" if значение > прежнее else "↓"
    из = {
        "банк": имя,
        "ставка": значение,
        "наблюдение": ряд[0]["date"] if ряд else None,
        "изменена": дата,
        "прежняя": прежнее,
        "направление": направление,
    }
    из.update(ещё)
    return из


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--verbose", action="store_true")
    a = p.parse_args()
    logging.basicConfig(level=logging.DEBUG if a.verbose else logging.INFO,
                        format="%(levelname)s %(message)s")
    # httpx печатает полный URL запроса, а в нём ключ FRED. Лог задачи
    # уезжает в journalctl, ключу там делать нечего.
    logging.getLogger("httpx").setLevel(logging.WARNING)

    верх = по_убыванию(series("DFEDTARU", ГЛУБИНА_ДНЕВНАЯ))
    низ = по_убыванию(series("DFEDTARL", ГЛУБИНА_ДНЕВНАЯ))
    ецб = по_убыванию(series("ECBDFR", ГЛУБИНА_ДНЕВНАЯ))
    мро = по_убыванию(series("ECBMRRFR", 2))
    япония = по_убыванию(series("IRSTCI01JPM156N", ГЛУБИНА_МЕСЯЧНАЯ))

    if not (верх and низ and ецб and япония):
        # 🔴 Молчать нельзя: пустой или частичный ответ FRED означает, что
        # станция покажет вчерашние данные как сегодняшние. Файл не
        # переписываем — старый честнее полупустого, — и выходим с ошибкой,
        # чтобы это увидел systemd, а не только лог.
        log.error("FRED отдал не всё: ФРС=%d/%d ЕЦБ=%d BoJ=%d — файл не тронут",
                  len(верх), len(низ), len(ецб), len(япония))
        return 1

    # 🔴 ПРОВЕРКА СВЕЖЕСТИ. Ошибка порядка выше дала данные трёхлетней
    # давности, и заметить это можно было только глазами. Теперь не только
    # глазами: дневные ряды обязаны быть не старше недели (праздники,
    # выходные, задержка публикации), месячный японский — не старше 70
    # дней: замер показал лаг 106 дней (июньская средняя опубликована к
    # сентябрю) — это нормальный ритм рядов OECD, и именно поэтому японское
    # число НЕЛЬЗЯ подписывать словом «сейчас»: месяц наблюдения обязан
    # стоять рядом со ставкой. Старое значение — это не «чуть менее
    # точно», это неверная станция с уверенной датой.
    сегодня = datetime.now(timezone.utc).date()
    for имя, ряд, предел in (("DFEDTARU", верх, 7), ("DFEDTARL", низ, 7),
                             ("ECBDFR", ецб, 7), ("IRSTCI01JPM156N", япония, 130)):
        возраст = (сегодня - datetime.fromisoformat(ряд[0]["date"]).date()).days
        if возраст > предел:
            log.error("%s: свежее наблюдение %s — %d дней назад при пределе %d. "
                      "Файл не тронут.", имя, ряд[0]["date"], возраст, предел)
            return 1

    банки = [
        запись("ФРС", верх[0]["value"], верх,
               код="DFEDTARU", диапазон=[низ[0]["value"], верх[0]["value"]],
               подпись_ставки=f"{низ[0]['value']:.2f}–{верх[0]['value']:.2f}%"),
        запись("ЕЦБ", ецб[0]["value"], ецб,
               код="ECBDFR", подпись_ставки=f"{ецб[0]['value']:.2f}%",
               мро=(мро[0]["value"] if мро else None),
               пояснение="ставка по депозитам — она направляет денежный рынок еврозоны"),
        запись("Банк Японии", япония[0]["value"], япония,
               код="IRSTCI01JPM156N", подпись_ставки=f"{япония[0]['value']:.2f}%",
               это_факт_а_не_цель=True,
               пояснение="фактическая ставка овернайт, средняя за месяц; "
                         "целевой ставки Банка Японии в FRED нет",
               месяц_наблюдения=япония[0]["date"][:7]),
    ]

    ВЫХОД.parent.mkdir(parents=True, exist_ok=True)
    ВЫХОД.write_text(json.dumps({
        "собрано": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "источник": "Federal Reserve Bank of St. Louis (FRED)",
        "банки": банки,
    }, ensure_ascii=False, indent=1), encoding="utf-8")

    for б in банки:
        log.info("%-12s %-14s %s с %s (было %s)", б["банк"], б["подпись_ставки"],
                 б["направление"], б["изменена"], б["прежняя"])
    log.info("записано: %s", ВЫХОД.relative_to(КОРЕНЬ))
    return 0


if __name__ == "__main__":
    sys.exit(main())
