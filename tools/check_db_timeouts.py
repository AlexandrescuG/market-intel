#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""check_db_timeouts.py — подключения к SQLite без ожидания блокировки.

🔴 ЗАЧЕМ. В core/db.py::_connect правило записано прямо и с обоснованием:
ждать 60 секунд, потому что «цена ожидания и цена отказа несимметричны —
подождать минуту ничего не стоит, а упавший прогон означает потерянные
прогнозы и несведённые сделки». Но само правило живёт в одной функции, а
подключений к той же базе в репозитории дюжина, и половина заведена мимо
неё. У соединения без `timeout` sqlite ждёт 5 секунд и бросает «database
is locked» — при том что писатель держит блокировку дольше.

Замер 29.09.2026: sbf-publish дал 42 падения из 231 прогона за сутки
(18%). Внешне это не поломка, а фон — и именно поэтому опасно: в потоке
таких сообщений перестают различаться настоящие остановки.

Это тот же класс, что подписи статусов лида в CRM, разъехавшиеся по
шести файлам: правило есть, копии о нём не знают.

Щуп намеренно простой — ищет текст, а не исполняет код: подключения
создаются в разных модулях, часть которых тянет за собой сеть и Wine.

Запуск:
    python3 tools/check_db_timeouts.py            # 1, если есть находки
    python3 tools/check_db_timeouts.py --все      # показать и корректные
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
МИНИМУМ = 30           # секунд; ниже — считаем, что ждать не собираются
ПРОПУСК = (".venv", "node_modules", "__pycache__", "backups")

# sqlite3.connect(...) до закрывающей скобки того же вызова.
ВЫЗОВ = re.compile(r"sqlite3\.connect\((?P<арг>[^()]*(?:\([^()]*\)[^()]*)*)\)")
ТАЙМАУТ = re.compile(r"timeout\s*=\s*(\d+)")
# timeout=<имя переменной>: значение решает вызывающий, и число тут не
# прочитать. Не находка — иначе щуп ругается на код, который как раз
# сделан настраиваемым (первый прогон дал 132 «беды» из 176, и почти всё
# это были :memory: и timeout=timeout).
ТАЙМАУТ_ПЕРЕМЕННОЙ = re.compile(r"timeout\s*=\s*[A-Za-zА-Яа-я_]")


def файлы():
    for п in КОРЕНЬ.rglob("*.py"):
        if any(ч in п.parts for ч in ПРОПУСК):
            continue
        yield п


def проверить() -> tuple[list[str], int]:
    беды: list[str] = []
    всего = 0
    for п in файлы():
        try:
            текст = п.read_text(encoding="utf-8")
        except OSError:
            continue
        if "sqlite3.connect" not in текст:
            continue
        строки = текст.splitlines()
        for м in ВЫЗОВ.finditer(текст):
            всего += 1
            номер = текст[:м.start()].count("\n") + 1
            отн = п.relative_to(КОРЕНЬ)
            арг = м.group("арг")
            # Соединение только на чтение блокировку писателя не ждёт —
            # ему достаточно снимка, и падать ему не на чем.
            # База в памяти вообще ни с кем не делится (тесты).
            if "mode=ro" in арг or ":memory:" in арг:
                continue
            if ТАЙМАУТ_ПЕРЕМЕННОЙ.search(арг):
                continue
            т = ТАЙМАУТ.search(арг)
            if т is None:
                беды.append(f"{отн}:{номер}: без timeout — ждать будет 5 с "
                            f"(дефолт sqlite)\n      {строки[номер - 1].strip()[:90]}")
            elif int(т.group(1)) < МИНИМУМ:
                беды.append(f"{отн}:{номер}: timeout={т.group(1)} с, "
                            f"минимум по правилу {МИНИМУМ}\n"
                            f"      {строки[номер - 1].strip()[:90]}")
    return беды, всего


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--все", action="store_true", help="показать и корректные")
    а = р.parse_args()

    беды, всего = проверить()
    for б in беды:
        print(f"✗ {б}")
    print(f"\nподключений найдено: {всего}, без нормального ожидания: {len(беды)}")
    if беды:
        print("Правило и его обоснование — в core/db.py::_connect. "
              "Либо звать его, либо повторять timeout=60 и busy_timeout.")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
