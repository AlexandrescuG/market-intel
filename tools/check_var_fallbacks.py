#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Фоллбэк в var(--токен, X) обязан совпадать со значением токена.

🔴 ЗАЧЕМ. Правя контраст, я менял значения в tokens.css и считал работу
сделанной. Но главы курса подключают brokers.css и НЕ подключают
tokens.css — переменных там нет, и в дело идёт фоллбэк. Фоллбэки остались
старыми, дореформенными: --ink-3 стал #736D63 (4.9:1 на белом), а в
brokers.css так и стоял var(--ink-3,#A8A29A) — 2.53:1. Замер на /brokers
показывал благополучие, потому что там токены есть; на главах тот же
класс давал 8 нарушений.

Фоллбэк — это значение «когда токенов нет», и оно обязано быть не хуже
самого токена. Проверка сверяет одно с другим по всем css-файлам.

Запуск: python3 tools/check_var_fallbacks.py
Код возврата 1, если нашлись расхождения.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
CSS = sorted((КОРЕНЬ / "web").rglob("*.css"))

# Объявления токенов: --имя: значение;
ОБЪЯВЛЕНИЕ = re.compile(r"(--[a-z0-9-]+)\s*:\s*([^;{}]+);")
# Использование с фоллбэком: var(--имя, значение)
ИСПОЛЬЗОВАНИЕ = re.compile(r"var\(\s*(--[a-z0-9-]+)\s*,\s*([^()]+?)\s*\)")


КОММЕНТАРИЙ = re.compile(r"/\*.*?\*/", re.S)
ЦВЕТ = re.compile(r"#[0-9a-f]{3,8}|rgba?\(|hsla?\(")


def норма(з: str) -> str:
    з = з.strip().lower()
    # #abc → #aabbcc, чтобы короткая запись не считалась расхождением
    if re.fullmatch(r"#[0-9a-f]{3}", з):
        з = "#" + "".join(c * 2 for c in з[1:])
    return з


def цвет(з: str) -> bool:
    """Расхождение в шрифте или отступе не про доступность — и правится
    по другим причинам. Смешивать их в одну кучу значит утопить цветовые
    находки в шуме из --h-mono."""
    return bool(ЦВЕТ.search(з.lower()))


def main() -> int:
    объявлены: dict[str, set[str]] = {}
    for ф in CSS:
        # Комментарии вырезаются ДО разбора: пояснение внутри правила
        # затягивалось в значение токена, и отчёт печатал абзац прозы
        # вместо цвета.
        текст = КОММЕНТАРИЙ.sub(" ", ф.read_text(encoding="utf-8", errors="replace"))
        for имя, знач in ОБЪЯВЛЕНИЕ.findall(текст):
            if "var(" in знач:          # токен через токен — не сверяем
                continue
            объявлены.setdefault(имя, set()).add(норма(знач))

    жёсткие: list[str] = []
    мягкие: list[str] = []
    for ф in CSS:
        исходник = ф.read_text(encoding="utf-8", errors="replace")
        for n, строка in enumerate(исходник.splitlines(), 1):
            for имя, фоллбэк in ИСПОЛЬЗОВАНИЕ.findall(КОММЕНТАРИЙ.sub(" ", строка)):
                эталон = объявлены.get(имя)
                if not эталон:
                    continue           # токен ниоткуда не объявлен — другой вопрос
                if норма(фоллбэк) in эталон:
                    continue
                строчка = (f"{ф.relative_to(КОРЕНЬ)}:{n}  {имя}: фоллбэк {фоллбэк} "
                           f"≠ объявленное {' / '.join(sorted(эталон))}")
                (жёсткие if цвет(фоллбэк) or any(map(цвет, эталон))
                 else мягкие).append(строчка)

    for с in жёсткие:
        print(с)
    if мягкие:
        print(f"\nНе про цвет ({len(мягкие)}) — шрифты и размеры, на контраст "
              f"не влияют:")
        for с in мягкие:
            print("  " + с)

    if жёсткие:
        print(f"\n✗ цветовых расхождений: {len(жёсткие)}. Фоллбэк работает там, "
              f"где нет tokens.css (главы курса) — он обязан быть не хуже токена.")
        return 1
    print(f"✓ фоллбэки совпадают с токенами ({len(объявлены)} токенов, "
          f"{len(CSS)} файлов)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
