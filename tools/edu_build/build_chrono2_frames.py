#!/usr/bin/env python3
"""Реальные ряды под станции хроники главы 2 → web/data/edu_capsules/chrono2_frames.json.

🔴 ЗАЧЕМ. Станции хроники рисовались ломаными от руки: `polyline points=
"220,140 300,150 340,145 ..."` — а подпись под такой ломаной стояла
настоящая, «Nikkei −12.4% за день, 05.08.2024». Придуманная линия с
настоящей подписью читается как график события. Это хуже, чем схема:
схему видно, что она схема, а ломаную с датой и процентом — нет.

Хуже того, у станции 2024 подпись называла Nikkei, а единственные данные,
которые у нас по этому дню есть, — USDJPY (в нашем бэкфилле Nikkei нет
вовсе, и сцена ch2_carry_2024 это прямо оговаривает). То есть подпись
обещала не тот инструмент, который был бы показан, даже если бы линию
рисовали по данным.

ЧТО ДЕЛАЕТ. Собирает по одному ряду на станцию и считает подпись ИЗ
САМОГО РЯДА — процент падения, даты, минимум и максимум. Ни одно число в
выходном файле не переписано из текста главы: если ряд скажет другое,
подпись будет другой, и это станет видно.

ИСТОЧНИКИ. Два вида, оба уже используются курсом:
  • готовые сцены на диске (web/data/edu_scenes/*.json) — там лежат
    настоящие свечи, собранные прошлыми сборщиками из тиков Dukascopy и
    бэкфилла MT5. Ходить за ними в сеть повторно незачем;
  • Yahoo Finance через tools/edu_build/_yahoo.py — для окон, которых на
    диске нет (1987, 1998, 2012, 2016).

ЧЕГО ЗДЕСЬ НЕТ. Станция 1980 («Волкер: ставка 20%») требует ряд ставки
ФРС. FRED с этой машины недоступен (ReadTimeout), а подставить вместо
ставки индекс — значит показать одно, а подписать другое. Поэтому у 1980
ряда нет, и выдуманную линию из неё просто убираем: иллюстрация без
графика честнее графика без данных.

Запуск: .venv/bin/python tools/edu_build/build_chrono2_frames.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ / "tools" / "edu_build"))

from _yahoo import fetch_daily  # noqa: E402

СЦЕНЫ = КОРЕНЬ / "web" / "data" / "edu_scenes"
ВЫХОД = КОРЕНЬ / "web" / "data" / "edu_capsules" / "chrono2_frames.json"

ТОЧЕК = 90          # столько закрытий максимум кладём в кадр: больше на
                    # 720×400 всё равно не различить, а файл растёт


def _проредить(ряд: list[dict], сколько: int = ТОЧЕК) -> list[dict]:
    """Равномерно проредить до `сколько` точек, сохранив первую и последнюю.

    🔴 Крайние точки берём всегда. Прореживание «каждый n-й» роняет
    последний бар, если длина не делится нацело, — а именно последний бар
    держит итоговое значение, по которому считается подпись.
    """
    if len(ряд) <= сколько:
        return ряд
    шаг = (len(ряд) - 1) / (сколько - 1)
    взято = [ряд[round(i * шаг)] for i in range(сколько)]
    взято[-1] = ряд[-1]
    return взято


def _с_экстремумами(ряд: list[dict], дата: str) -> list[dict]:
    """Подменить точку события её внутридневными экстремумами.

    🔴 ИНАЧЕ ПОДПИСЬ И ОСЬ МЕРЯЮТ РАЗНОЕ. Подписи станций 2016 и 2024
    называют внутридневной ход: «размах дня 118.52 → 121.66», «дно 141.7».
    Ряд же строился по закрытиям — и ось кадра честно показывала, что цена
    ниже 144.68 не опускалась, ровно под подписью про 141.7. Два числа про
    один день, посчитанные разными линейками, и читатель видит оба сразу.
    Поэтому день события входит в ряд двумя точками — экстремумами, в
    порядке хода: если день шёл вниз, сначала максимум, потом минимум.
    Линия в этом месте даёт настоящий шип, а не сглаженную ступеньку.
    """
    вышло = []
    for i, b in enumerate(ряд):
        if b["time"][:10] != дата or "high" not in b or "low" not in b:
            вышло.append(b)
            continue
        низ, верх = float(b["low"]), float(b["high"])
        пред = float(ряд[i - 1]["close"]) if i else float(b["open"])
        вниз = abs(низ - пред) > abs(верх - пред)
        for v in ([верх, низ] if вниз else [низ, верх]):
            вышло.append({"time": b["time"], "close": v})
        вышло.append({"time": b["time"], "close": float(b["close"])})
    return вышло


def _кадр(имя: str, подпись: str, источник: str, ряд: list[dict],
          отметка: str | None = None, единица: str = "") -> dict:
    """Кадр станции: только закрытия, крайние значения и посчитанная подпись."""
    точки = [{"t": b["time"][:10], "c": round(float(b["close"]), 5)} for b in ряд]
    цены = [т["c"] for т in точки]
    return {
        "станция": имя,
        "подпись": подпись,
        "источник": источник,
        "единица": единица,
        "отметка": отметка,
        "точек": len(точки),
        "мин": min(цены),
        "макс": max(цены),
        "первая": точки[0]["t"],
        "последняя": точки[-1]["t"],
        "ряд": _проредить(точки),
    }


def _середины(ряд: list[dict]) -> list[dict]:
    """Ряд, где вместо ненадёжного закрытия стоит середина дневного диапазона.

    Нужен там же, где и _размах_дня: рисовать линию по полю close, которое
    дублирует open, значит показать ступеньки вместо движения цены.
    """
    return [{"time": b["time"], "close": (float(b["high"]) + float(b["low"])) / 2}
            for b in ряд]


def _середины_с_ohlc(ряд: list[dict]) -> list[dict]:
    """Середины дневного диапазона, но с сохранёнными high/low.

    Нужны обе вещи сразу: линию рисуем по серединам (close у Yahoo в FX
    ненадёжен), а день события показываем экстремумами — значит high и low
    должны дожить до _с_экстремумами, а не потеряться по дороге.
    """
    return [{"time": b["time"], "open": b["open"], "high": b["high"],
             "low": b["low"],
             "close": (float(b["high"]) + float(b["low"])) / 2} for b in ряд]


def _бар(ряд: list[dict], дата: str) -> dict:
    """Бар за конкретный день. Нет такого дня — падаем, а не берём соседний.

    Молча сдвинуть день на соседний значит подписать чужое число.
    """
    for b in ряд:
        if b["time"][:10] == дата:
            return b
    raise SystemExit(f"нет бара за {дата}: в ряду {ряд[0]['time'][:10]}"
                     f"…{ряд[-1]['time'][:10]}")


def _падение(ряд: list[dict], дата: str) -> tuple[float, float, float]:
    """Изменение за день по закрытиям: от закрытия предыдущего дня к этому.

    Годится только там, где закрытию можно верить, — у нас это индексы с
    Yahoo и свечи из собственного бэкфилла. Для валютных пар с Yahoo —
    см. _размах_дня.
    """
    индексы = {b["time"][:10]: i for i, b in enumerate(ряд)}
    if дата not in индексы:
        raise SystemExit(f"нет бара за {дата}: в ряду {ряд[0]['time'][:10]}"
                         f"…{ряд[-1]['time'][:10]}")
    i = индексы[дата]
    if i == 0:
        raise SystemExit(f"{дата} — первый бар ряда, не с чем сравнивать")
    было, стало = float(ряд[i - 1]["close"]), float(ряд[i]["close"])
    return (стало / было - 1) * 100, было, стало


def _размах_дня(ряд: list[dict], дата: str) -> tuple[float, float, float]:
    """Минимум и максимум дня и ход между ними, в процентах.

    🔴 ПОЧЕМУ ПО ЭКСТРЕМУМАМ, А НЕ ПО ЗАКРЫТИЯМ. У Yahoo в валютных парах
    (JPY=X, EURUSD=X) поле close дублирует open того же дня: 29.01.2016
    отдаётся как o=118.93 c=118.93 при том, что внутри дня цена дошла до
    121.66. Посчитанное по закрытиям «дневное изменение» дало +0.39% —
    правдоподобное число, полностью скрывающее событие: в тот день BoJ
    увёл ставку ниже нуля и пара прошла почти три процента.
    Экстремумы Yahoo при этом настоящие — по ним и считаем, а подпись
    прямо называет то, что посчитано: размах дня, а не «изменение».
    Проверять это надо на каждой новой паре: у индексов (^GSPC) закрытия
    в порядке, артефакт именно валютный.
    """
    b = _бар(ряд, дата)
    низ, верх = float(b["low"]), float(b["high"])
    return (верх / низ - 1) * 100, низ, верх


def _сцена(имя: str) -> dict:
    return json.loads((СЦЕНЫ / f"{имя}.json").read_text(encoding="utf-8"))


def собрать() -> dict:
    кадры = {}

    # ── 1987: чёрный понедельник ────────────────────────────────────────
    # 🔴 Подпись станции говорила «−22.6% за день» — это Dow. У нас ряд
    # S&P 500, и он упал в тот день на другую величину. Считаем по своему
    # ряду и называем свой индекс: перенести число Dow на график S&P —
    # ровно та ошибка, из-за которой всё это и переделывается.
    spx87 = fetch_daily("^GSPC", "1987-09-15", "1987-11-20")
    пад, было, стало = _падение(spx87, "1987-10-19")
    кадры["1987_blackmonday"] = _кадр(
        "1987_blackmonday",
        f"S&P 500: {пад:.1f}% за день, 19 октября 1987 ({было:.0f} → {стало:.0f})",
        "Yahoo Finance, ^GSPC, дневные",
        spx87, отметка="1987-10-19", единица="пункты")

    # ── 1998: LTCM ──────────────────────────────────────────────────────
    spx98 = fetch_daily("^GSPC", "1998-07-01", "1998-10-31")
    пик = max(spx98, key=lambda b: b["close"])
    дно = min([b for b in spx98 if b["time"] > пик["time"]] or spx98,
              key=lambda b: b["close"])
    прос = (float(дно["close"]) / float(пик["close"]) - 1) * 100
    кадры["1998_ltcm"] = _кадр(
        "1998_ltcm",
        f"S&P 500: {прос:.1f}% от пика {пик['time'][:10]} ко дну {дно['time'][:10]}",
        "Yahoo Finance, ^GSPC, дневные",
        spx98, отметка=дно["time"][:10], единица="пункты")

    # ── 2012: «whatever it takes» ───────────────────────────────────────
    # Валютная пара с Yahoo — считаем по экстремумам дня, не по закрытиям
    # (см. _размах_дня), и рисуем середину дневного диапазона.
    eur12 = fetch_daily("EURUSD=X", "2012-07-01", "2012-09-10")
    ход, низ, верх = _размах_дня(eur12, "2012-07-26")
    кадры["2012_draghi"] = _кадр(
        "2012_draghi",
        f"EURUSD в день речи Драги, 26.07.2012: размах дня "
        f"{низ:.4f} → {верх:.4f} ({ход:+.2f}%)",
        "Yahoo Finance, EURUSD=X, дневные (середина диапазона, день события — экстремумы)",
        _с_экстремумами(_середины_с_ohlc(eur12), "2012-07-26"),
        отметка="2012-07-26", единица="EURUSD")

    # ── 2015: SNB отменяет пол ──────────────────────────────────────────
    # Ряд уже на диске: 838 настоящих свечей из тиков Dukascopy.
    snb = _сцена("ch2_snb_2015")
    свечи = snb["candles"]
    до = [b for b in свечи if b["time"] < "2015-01-15T09:30:00Z"]
    после = [b for b in свечи if b["time"] >= "2015-01-15T09:30:00Z"]
    пад = (min(float(b["low"]) for b in после) / float(до[-1]["close"]) - 1) * 100
    кадры["2015_snb"] = _кадр(
        "2015_snb",
        f"EURCHF: пол 1.20 снят 15.01.2015, дно дня {пад:.1f}% от последней цены пола",
        "Dukascopy, тики → минутные свечи (сцена ch2_snb_2015)",
        [{"time": b["time"], "close": b["close"]} for b in свечи],
        отметка="2015-01-15", единица="EURCHF")

    # ── 2016: BoJ уводит ставку ниже нуля ───────────────────────────────
    jpy16 = fetch_daily("JPY=X", "2016-01-15", "2016-02-19")
    ход, низ, верх = _размах_дня(jpy16, "2016-01-29")
    кадры["2016_boj"] = _кадр(
        "2016_boj",
        f"USDJPY в день решения BoJ, 29.01.2016: размах дня "
        f"{низ:.2f} → {верх:.2f} ({ход:+.2f}%)",
        "Yahoo Finance, JPY=X, дневные (середина диапазона, день события — экстремумы)",
        _с_экстремумами(_середины_с_ohlc(jpy16), "2016-01-29"),
        отметка="2016-01-29", единица="USDJPY")

    # ── 2022–23: цикл ФРС ───────────────────────────────────────────────
    # Здесь ряд — не цена, а сама ставка: 12 заседаний FOMC с решением и
    # уровнем после него. Ступенька рисуется по ним, а не «на глаз».
    цикл = _сцена("ch2_cycle_2022")["fomc_meetings"]

    def верх(диапазон: str) -> float:
        return float(диапазон.rstrip("%").split("-")[-1])

    точки = [{"t": m["date"], "c": верх(m["rate_after"])} for m in цикл]
    кадры["2022_cycle"] = {
        "станция": "2022_cycle", "единица": "% годовых",
        "подпись": (f"Цикл ФРС: {len(цикл)} заседаний, "
                    f"{точки[0]['c']:.2f}% → {точки[-1]['c']:.2f}% "
                    f"({точки[0]['t']} → {точки[-1]['t']})"),
        "источник": "Решения FOMC (сцена ch2_cycle_2022)",
        "отметка": точки[-1]["t"], "точек": len(точки),
        "мин": min(т["c"] for т in точки), "макс": max(т["c"] for т in точки),
        "первая": точки[0]["t"], "последняя": точки[-1]["t"], "ряд": точки,
        "ступенька": True,
    }

    # ── 2024: разворот кэрри-трейда ─────────────────────────────────────
    # 🔴 Подпись станции говорила про Nikkei. Nikkei у нас нет — ни в
    # бэкфилле, ни в сцене; сцена прямо это оговаривает и показывает
    # USDJPY. Значит и подпись должна говорить USDJPY.
    # 🔴 И событие здесь — не дневное изменение, а провал ВНУТРИ дня.
    # 5 августа пара открылась на 145.67, сходила на 141.69 и закрылась на
    # 145.80: по закрытиям выходит +0.13%, то есть «ничего не произошло».
    # Число правдивое и совершенно пустое — ровно тот случай, когда
    # линейка сглаживает то, ради чего станцию и показывают. Считаем ход
    # от вершины перед разворотом к минимуму того дня.
    # 🔴 Подпись считается по ТОМУ ЖЕ ряду, который пойдёт в кадр.
    # Первая версия брала вершину по полю high всех баров (158.8 на 16.07),
    # а рисовался ряд по закрытиям — и ось кадра доходила только до 158.36.
    # Разница в четыре десятых, зато ровно того сорта, из-за которого всё
    # это переделывается: подпись называет точку, которой на картинке нет.
    carry = _с_экстремумами(_сцена("ch2_carry_2024")["candles"], "2024-08-05")
    день = _бар(carry, "2024-08-05")
    вершина = max(carry[:carry.index(день)] or carry, key=lambda b: float(b["close"]))
    дно = min((b for b in carry if b["time"][:10] == "2024-08-05"),
              key=lambda b: float(b["close"]))
    ход = (float(дно["close"]) / float(вершина["close"]) - 1) * 100
    кадры["2024_boj"] = _кадр(
        "2024_boj",
        f"USDJPY: {float(вершина['close']):.1f} ({вершина['time'][:10]}) → "
        f"{float(дно['close']):.1f} (05.08.2024), {ход:.1f}%; "
        f"закрытие дня {float(carry[-1]['close']):.1f}",
        "market_intel MT5 backfill (сцена ch2_carry_2024)",
        carry, отметка="2024-08-05", единица="USDJPY")

    return кадры


def main() -> None:
    кадры = собрать()
    ВЫХОД.parent.mkdir(parents=True, exist_ok=True)
    ВЫХОД.write_text(json.dumps({
        "meta": {
            "что": "Реальные ряды под станции хроники главы 2",
            "правило": "все числа в подписях посчитаны из самого ряда",
            "без_данных": {"1980_volcker": "ставка ФРС 1979-82; FRED недоступен"},
        },
        "кадры": кадры,
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"кадров: {len(кадры)} → {ВЫХОД.relative_to(КОРЕНЬ)}")
    for к in кадры.values():
        print(f"   {к['станция']:18} {к['точек']:4} точек  {к['подпись']}")


if __name__ == "__main__":
    main()
