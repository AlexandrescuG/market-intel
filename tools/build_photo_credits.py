#!/usr/bin/env python3
"""Строки атрибуции под фотографиями — из манифеста, а не руками.

🔴 ЗАЧЕМ. Семь снимков хроники лежат под CC-BY / CC-BY-SA. Эти лицензии
разрешают показ ровно при условии видимой атрибуции: имя автора и название
лицензии там, где видно читателю. У нас автор лежал только в
web/edu/assets/history/manifest.json — файле, который читатель никогда не
открывает. То есть условие лицензии не выполнялось, хотя вся нужная
информация была собрана и записана.

🔴 ПОЧЕМУ ГЕНЕРАТОР, А НЕ РУКИ. Переписать четырнадцать записей вручную —
это четырнадцать возможностей ошибиться в фамилии или в версии лицензии,
причём ошибка в атрибуции хуже её отсутствия: она называет неверного
автора. Манифест остаётся единственным источником правды, а этот скрипт
переносит из него ровно то, что нужно показать.

Результат: web/edu/assets/history/credits.json — {станция: {автор, лицензия,
ссылка}} — который грузит chrono.js.

Запуск: python3 tools/build_photo_credits.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
МАНИФЕСТ = КОРЕНЬ / "web" / "edu" / "assets" / "history" / "manifest.json"
ВЫХОД = КОРЕНЬ / "web" / "edu" / "assets" / "history" / "credits.json"


def короткая_лицензия(полная: str) -> str:
    """«CC BY-SA 3.0 (Creative Commons…)» → «CC BY-SA 3.0».

    Показывать читателю абзац юридического текста незачем — нужно название
    лицензии, по которому её можно найти. Полная формулировка остаётся в
    манифесте.
    """
    м = re.match(r"(CC0 1\.0|CC BY(?:-SA)?(?:-NC)? ?[\d.]*)", полная.strip())
    if м:
        return м.group(1).strip()
    if полная.lower().startswith("public domain"):
        return "Public Domain"
    return полная.split("(")[0].strip()[:40]


def нужна_атрибуция(лицензия: str) -> bool:
    """CC BY и CC BY-SA требуют указания автора. PD и CC0 — нет.

    Для PD автора всё равно показываем, когда он известен: это не
    обязанность, а обычная вежливость к источнику и польза читателю —
    «Эмануэль де Витте, 1653» говорит о картинке больше, чем её отсутствие.
    """
    return лицензия.upper().startswith("CC BY")


def main() -> None:
    записи = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
    вышло = {}
    for r in записи:
        лиц = короткая_лицензия(r.get("license", ""))
        автор = (r.get("author") or "").strip()
        # Пояснение в скобках нужно манифесту, а в подписи под фото мешает:
        # живой замер показал «Anonymous Dutch engraver (satirical print s…» —
        # строка обрезается многоточием ровно посреди пояснения и выглядит
        # поломкой. Скобка в этом поле всегда описание, а не часть имени:
        # годы жизни, роль («engraver»), источник, номер патента. Полная
        # запись остаётся в манифесте, читателю нужно имя.
        # Составная запись «Object: …; Photo: …» описывает предмет и снимок
        # разными людьми. Под фотографией уместен автор снимка — предмет
        # описан в самой станции.
        for кусок in автор.split(";"):
            if кусок.strip().lower().startswith("photo:"):
                автор = кусок.split(":", 1)[1]
                break
        автор = автор.split(" (")[0].strip().rstrip(",")
        вышло[r["station"]] = {
            "автор": автор,
            "лицензия": лиц,
            "ссылка": r.get("source_url", ""),
            "обязательна": нужна_атрибуция(лиц),
        }
    ВЫХОД.write_text(json.dumps({"кредиты": вышло}, ensure_ascii=False, indent=1),
                     encoding="utf-8")
    обяз = sum(1 for v in вышло.values() if v["обязательна"])
    print(f"записей: {len(вышло)} → {ВЫХОД.relative_to(КОРЕНЬ)}")
    print(f"из них атрибуция обязательна (CC BY*): {обяз}")
    for с, v in вышло.items():
        метка = "CC-BY" if v["обязательна"] else "  —  "
        print(f"   {метка} {с:18} {v['автор'][:32]:32} {v['лицензия']}")


if __name__ == "__main__":
    main()
