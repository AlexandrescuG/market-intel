#!/usr/bin/env python3
"""Проверка расчёта часов на КОПИИ базы с посевом. Боевые данные не трогаем.

🔴 КОНТРОЛЬ С ИЗВЕСТНЫМ ОТВЕТОМ. Сеем сделки так, чтобы правильный ответ был
известен заранее: входы кучнее всего в 14 часов, а зарабатывают 9 часов.
Если расчёт скажет что-то другое — виноват расчёт, а не данные. Без такого
посева «часы посчитались» означает только, что код не упал.

Запуск: python3 tools/test_journal_hours.py
"""
from __future__ import annotations

import random
import shutil
import sqlite3
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from core import journal_hours as jh  # noqa: E402

ИСХОД = КОРЕНЬ / "data" / "journal.db"
КОПИЯ = Path("/tmp/journal_hours_test.db")


def посеять(путь: Path, людей: int, сделок_на_человека: int) -> None:
    c = sqlite3.connect(str(путь))
    c.execute("DELETE FROM trades")
    n = 0
    # 🔴 РАСПРЕДЕЛЕНИЕ ЗАДАНО ЯВНО, А НЕ СЛУЧАЙНО.
    # Первая версия раскидывала «остальные» часы через random.choice, и на
    # 40 сделках в 9 часов попало две штуки — меньше порога МИН_СДЕЛОК_В_ЧАСЕ.
    # Расчёт совершенно правильно отказался называть такой час лучшим и выбрал
    # 11:00 с шестью сделками, а проверка объявила это провалом. Виноват был
    # посев: контроль с известным ответом обязан этот ответ ГАРАНТИРОВАТЬ, а
    # не надеяться на удачную выборку. Теперь 14 и 9 набирают заведомо больше
    # порога, и проверка меряет расчёт, а не везение генератора.
    расписание = ([14] * 6 + [9] * 3 + [10, 16])   # 11 сделок в цикле
    for i in range(людей):
        uid = f"проба{i}"
        for j in range(сделок_на_человека):
            час = расписание[j % len(расписание)]
            # Результат: в 9 часов стабильный плюс, в 14 — стабильный минус.
            r = 0.9 if час == 9 else (-0.3 if час == 14 else 0.05)
            n += 1
            c.execute(
                """INSERT INTO trades(user_id,symbol,dir,entry_price,exit_price,
                   size,open_ts,close_ts,pnl,pnl_r,fees,source,import_hash,note)
                   VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (uid, "TEST", "buy", 100.0, 101.0, 1.0,
                 f"2026-08-{(j % 27) + 1:02d} {час:02d}:05:00",
                 f"2026-08-{(j % 27) + 1:02d} {час:02d}:45:00",
                 r, r, 0.0, "manual", f"h{i}_{j}", ""))
    c.commit()
    c.close()
    print(f"посеяно: {людей} человек × {сделок_на_человека} = {n} сделок")


def main() -> None:
    shutil.copy(ИСХОД, КОПИЯ)

    print("\n── 1. Мало сделок: порог обязан сработать")
    посеять(КОПИЯ, людей=1, сделок_на_человека=5)
    d = jh.свои_часы("проба0", путь=КОПИЯ)
    print(f"   available={d['available']} сделок={d['trade_count']} "
          f"нужно={d.get('нужно_сделок')}")
    assert d["available"] is False, "порог не сработал"

    print("\n── 2. Достаточно сделок: ждём вход в 14, заработок в 9")
    посеять(КОПИЯ, людей=1, сделок_на_человека=40)
    d = jh.свои_часы("проба0", путь=КОПИЯ)
    print(f"   available={d['available']} сделок={d['trade_count']}")
    print(f"   чаще всего входит в {d['час_входов']}:00 "
          f"({d['сделок_в_нём']} сделок, {d['r_в_нём']} R)")
    print(f"   зарабатывает в {d['час_заработка']}:00 "
          f"({d['сделок_в_лучшем']} сделок, {d['r_в_лучшем']} R)")
    print(f"   совпадают: {d['совпадают']}")
    assert d["час_входов"] == 14, f"ждали 14, получили {d['час_входов']}"
    assert d["час_заработка"] == 9, f"ждали 9, получили {d['час_заработка']}"
    assert d["совпадают"] is False

    print("\n── 3. Платформа: порог по людям и сделкам")
    посеять(КОПИЯ, людей=10, сделок_на_человека=40)   # 400 сделок, 10 человек
    d = jh.часы_платформы(путь=КОПИЯ)
    print(f"   available={d['available']} людей={d['n_users']} "
          f"сделок={d['n_trades']} (порог {d.get('нужно_пользователей')}/"
          f"{d.get('нужно_сделок')})")
    assert d["available"] is False, "порог платформы не сработал"

    посеять(КОПИЯ, людей=60, сделок_на_человека=30)   # 1800 сделок, 60 человек
    d = jh.часы_платформы(путь=КОПИЯ)
    print(f"   available={d['available']} людей={d['n_users']} "
          f"сделок={d['n_trades']}")
    print(f"   вход {d['час_входов']}:00 · заработок {d['час_заработка']}:00")
    assert d["available"] is True
    assert d["час_входов"] == 14 and d["час_заработка"] == 9

    print("\n── 4. Боевая база не тронута")
    c = sqlite3.connect(str(ИСХОД))
    n = c.execute("SELECT COUNT(*) FROM trades").fetchone()[0]
    c.close()
    print(f"   сделок в проде: {n}")

    print("\nВСЕ ПРОВЕРКИ ПРОШЛИ")


if __name__ == "__main__":
    main()
