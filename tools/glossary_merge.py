#!/usr/bin/env python3
"""tools/glossary_merge.py — слияние терминов в три словаря и их проверка.

ЗАЧЕМ. Словарь живёт в ТРЁХ файлах (`web/assets/glossary.json`,
`glossary.ro.json`, `glossary.en.json`), и это не копии текста, а три
локали одного справочника. Добавлять термин руками в три файла — верный
способ получить 150 статей на русском и 140 на румынском, причём узнать
об этом от читателя. Поэтому партия терминов описывается ОДНОЙ
структурой на все языки, а раскладывает её по файлам этот модуль.

🔴 МАШИННЫЙ ПЕРЕВОД ЗДЕСЬ ЗАПРЕЩЁН, И ЭТО НЕ ПРЕДОСТОРОЖНОСТЬ.
Замер 07.10.2026: цепочка переводчиков превращает «нефть WTI» в «ITC
brut», а «Hormuz Uncertainty Offsets Saudi Recovery» — в «пролив СНИМАЕТ
неопределённость», то есть переворачивает смысл. Для справочника, где
статья НАЗЫВАЕТ инструмент, искажённый тикер хуже отсутствия статьи:
читатель ищет WTI и не находит. Все три языка пишутся руками.

Проверки, которые модуль делает сам (по одной на каждую ошибку, которую
легко сделать и невозможно заметить глазами в файле на 200 статей):
  • slug уникален и совпадает во всех трёх локалях;
  • состав терминов в локалях одинаков — ни одна статья не потерялась;
  • related ведёт на существующий slug (иначе ссылка «по теме» в никуда,
    ровно находка К-1 сентябрьского аудита: 7 ссылок на несуществующие
    статьи);
  • alias не присвоен двум разным статьям: подсветка в тексте берёт
    первое совпадение, и один alias на два термина — это молча неверная
    карточка на странице главы;
  • в ro/en нет кириллицы, в ru есть (ловит незаполненный перевод);
  • section из известного списка.

Запуск самостоятельно — только проверка уже лежащего:
    python3 tools/glossary_merge.py --check
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ФАЙЛЫ = {
    "ru": КОРЕНЬ / "web/assets/glossary.json",
    "ro": КОРЕНЬ / "web/assets/glossary.ro.json",
    "en": КОРЕНЬ / "web/assets/glossary.en.json",
}
ЯЗЫКИ = ("ru", "ro", "en")

# Разделы. Ключ — в данных, подписи — в i18n (glossary.sec_*), чтобы
# название раздела не оказалось четвёртой копией строки.
РАЗДЕЛЫ = (
    "technical",   # графика, индикаторы, фигуры
    "macro",       # макроданные и центробанки
    "options",     # опционы и греки
    "bonds",       # облигации, ставки, кривая доходности
    "futures",     # фьючерсы, сырьё, срочная кривая
    "fx",          # валютный рынок
    "equity",      # акции и отчётность
    "crypto",      # криптоактивы
    "risk",        # риск, метрики портфеля
    "micro",       # микроструктура и исполнение
    "brokers",     # брокеры, регуляторы, типы счетов
    "slang",       # сленг рынка
)

КИРИЛЛИЦА = re.compile(r"[А-Яа-яЁё]")
ПОЛЯ_ТЕКСТА = ("term", "short", "full", "etym")


def читать() -> dict[str, list[dict]]:
    return {я: json.loads(ФАЙЛЫ[я].read_text(encoding="utf-8")) for я in ЯЗЫКИ}


def писать(словари: dict[str, list[dict]]) -> None:
    for я in ЯЗЫКИ:
        # Порядок в файле — по slug: diff между правками остаётся читаемым,
        # а порядок на странице всё равно задаёт сортировка по алфавиту
        # нужной локали, не порядок в файле.
        данные = sorted(словари[я], key=lambda т: т["slug"])
        ФАЙЛЫ[я].write_text(
            json.dumps(данные, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )


def проверить(словари: dict[str, list[dict]], related: bool = True) -> list[str]:
    """related=False — не сверять ссылки «по теме».

    🔴 Нужно РОВНО для одного случая: партия терминов ссылается вперёд, на
    статьи из следующей партии. Запрещать это значит писать словарь в
    порядке, в котором связи не идут вперёд, — то есть не писать его вовсе.
    Послабление безопасно только потому, что финальный `--check` сверяет
    ссылки всегда и без флага: незаполненная связь не доедет до прода
    молча, она свалит проверку. Если когда-нибудь этот флаг появится в
    самом `--check`, смысл проверки исчезнет.
    """
    беды: list[str] = []

    слаги = {я: [т.get("slug") for т in словари[я]] for я in ЯЗЫКИ}
    for я in ЯЗЫКИ:
        дубли = {с for с in слаги[я] if слаги[я].count(с) > 1}
        if дубли:
            беды.append(f"{я}: slug повторяется — {sorted(дубли)}")
        пустые = [т.get("term") for т in словари[я] if not т.get("slug")]
        if пустые:
            беды.append(f"{я}: статья без slug — {пустые[:5]}")

    эталон = set(слаги["ru"])
    for я in ("ro", "en"):
        нет = эталон - set(слаги[я])
        лишние = set(слаги[я]) - эталон
        if нет:
            беды.append(f"{я}: НЕТ статей, которые есть в ru — {sorted(нет)[:8]}")
        if лишние:
            беды.append(f"{я}: лишние статьи, которых нет в ru — {sorted(лишние)[:8]}")

    for я in ЯЗЫКИ:
        известные = set(слаги[я])
        for т in словари[я]:
            # related в никуда
            if related:
                for с in т.get("related") or []:
                    if с not in известные:
                        беды.append(f"{я}/{т['slug']}: related → «{с}», такой статьи нет")
            # раздел
            if т.get("section") not in РАЗДЕЛЫ:
                беды.append(f"{я}/{т['slug']}: section «{т.get('section')}» неизвестен")
            # обязательные поля
            for поле in ("term", "short", "full"):
                if not (т.get(поле) or "").strip():
                    беды.append(f"{я}/{т['slug']}: пустое поле {поле}")
            # длины: short — одна фраза для попапа, full — абзац
            if len(т.get("short") or "") > 160:
                беды.append(f"{я}/{т['slug']}: short длиннее 160 знаков, это не подпись")

        # alias на две статьи
        чей: dict[str, str] = {}
        for т in словари[я]:
            for a in (т.get("aliases") or []):
                к = a.lower().strip()
                if к in чей and чей[к] != т["slug"]:
                    беды.append(
                        f"{я}: alias «{a}» и у {чей[к]}, и у {т['slug']} — "
                        "подсветка возьмёт первый и покажет не ту карточку"
                    )
                чей[к] = т["slug"]

    # Язык: в ro/en кириллицы быть не должно, в ru — должна (кроме статей,
    # чьё имя целиком латиницей: RSI, MACD, SMC и подобные).
    for я in ("ro", "en"):
        for т in словари[я]:
            for поле in ПОЛЯ_ТЕКСТА:
                v = т.get(поле) or ""
                if КИРИЛЛИЦА.search(v):
                    беды.append(f"{я}/{т['slug']}: кириллица в {поле} — перевода нет")
                    break
    return беды


def влить(партия: list[dict], related: bool = True) -> None:
    """партия: [{slug, section, related, ru:{...}, ro:{...}, en:{...}}, …]"""
    словари = читать()
    было = len(словари["ru"])
    for запись in партия:
        слаг = запись["slug"]
        for я in ЯЗЫКИ:
            часть = запись[я]
            статья = {
                "slug": слаг,
                "term": часть["term"],
                "aliases": часть.get("aliases") or [],
                "short": часть["short"],
                "full": часть["full"],
                "related": запись.get("related") or [],
                "etym": часть.get("etym") or "",
                "section": запись["section"],
            }
            # Повторный прогон партии не плодит дубли, а обновляет статью.
            остальные = [т for т in словари[я] if т.get("slug") != слаг]
            остальные.append(статья)
            словари[я] = остальные
    беды = проверить(словари, related=related)
    if беды:
        print("✗ НЕ ЗАПИСАНО, сначала починить:")
        for b in беды:
            print("   ", b)
        sys.exit(1)
    писать(словари)
    print(f"✓ влито {len(партия)}; статей было {было}, стало {len(словари['ru'])}")


if __name__ == "__main__":
    if "--check" in sys.argv:
        беды = проверить(читать())
        if беды:
            print(f"✗ находок: {len(беды)}")
            for b in беды:
                print("   ", b)
            sys.exit(1)
        д = читать()
        from collections import Counter

        по = Counter(т.get("section") for т in д["ru"])
        print(f"✓ чисто. статей: {len(д['ru'])} × 3 локали")
        for с in РАЗДЕЛЫ:
            print(f"    {с:10} {по.get(с, 0)}")
        if по.get(None):
            print(f"    {'БЕЗ РАЗДЕЛА':10} {по[None]}")
