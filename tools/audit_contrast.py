# -*- coding: utf-8 -*-
"""audit_contrast.py — сколько текста на сайте не проходит AA по контрасту.

🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ, А НЕ «ПОСЧИТАТЬ В УМЕ».
Аудит 03.09 записал `--muted` как 4.58:1 и закрыл вопрос. Это отношение
к БЕЛОМУ. Фон страницы у нас кремовый (#FBF6EF), и на нём тот же цвет даёт
4.26:1 — ниже порога 4.5. Один неверно выбранный фон превратил «проходит»
в «не проходит» и спрятал находку на две недели.

Поэтому фон здесь не назначается, а ИЩЕТСЯ: скрипт поднимается по предкам
до первого непрозрачного background-color, как это делает axe. Если по пути
встретилась полупрозрачная подложка — цвет смешивается, а не берётся as is.

Порог: 4.5:1 для обычного текста, 3.0:1 для крупного (≥24px или ≥18.66px
жирный) — WCAG 2.1 AA, 1.4.3.

Что НЕ проверяется и почему: элементы без собственного текстового узла
(контраст наследуется и был бы посчитан дважды), невидимое, полностью
прозрачный текст, выключенные элементы управления и aria-hidden (WCAG
выводит их из-под требования), и текст поверх картинки (фон там не цвет —
такие места надо смотреть глазами, скрипт их отдельно пересчитывает
в «пропущено»).

Известное ограничение: у текста внутри SVG за фон принимается фон HTML-
контейнера. Если подпись лежит поверх залитого <rect>, настоящий фон —
заливка прямоугольника, и число будет оптимистичнее правды. Такие места
проверяются глазами по снимку, а не этим скриптом.

Запуск:
    python3 tools/audit_contrast.py                 # все страницы
    python3 tools/audit_contrast.py --url /journal  # одна
    python3 tools/audit_contrast.py --json до.json  # сохранить замер
    python3 tools/audit_contrast.py --diff до.json  # сравнить с замером
"""
from __future__ import annotations

