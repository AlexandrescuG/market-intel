import json
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

КОРЕНЬ = Path(__file__).resolve().parents[1]
БАЗА = "http://127.0.0.1:8085"

# Страницы, доступные без входа. За логином (/journal, /admin) меряется
# отдельно — туда нужна живая сессия, и делать её в этом скрипте значило бы
# завести пароль в код.
# 🔴 Пути проверены не глазами, а прогоном: список ошибался ДВАЖДЫ, и оба
# раза ошибка выглядела как хорошая новость.
#   1) «/chart», «/book/1» — 404. Страница 404 содержит 4 элемента с текстом,
#      замер отрапортовал «ноль нарушений» по самым текстовым разделам сайта.
#   2) «/book/edu_book_N.html» — 200 и 73 КБ, но это ИСХОДНИК шаблона: файл
#      отдаётся статикой, Jinja его не трогает, и в браузере падает Babel на
#      «{% raw %}». Ноль элементов при 73 КБ ответа.
# Главы рендерятся только через маршрут _EDU_RE: /edu/b/N.
# Список сверен с постраничной картой аудита (AUDIT_lp_pages_2026-09-16):
# все анонимные страницы + по одной языковой версии там, где румынские
# подписи длиннее русских. За логином (/journal, /admin) меряется отдельно.
СТРАНИЦЫ = [
    "/",
    "/brokers",
    "/brokers/xm",
    "/glossary",
    "/privacy",
    "/grafik?s=EURUSD",
    "/edu",
    "/edu/calendar",
    # 🔴 ВСЕ 15 глав, а не выборка. Раньше здесь стояли 1, 2 и 10, и после
    # правок отчёт показывал «0 нарушений по сайту». Это было неправдой по
    # умолчанию: главы 3-9 и 11-15 просто не мерились, а в главе 3 их 38 —
    # те же тёмные панели, что чинились в главе 2. Выборка из трёх глав
    # отвечала на вопрос «как дела в трёх главах», а печаталась как «по
    # сайту». Прогон дольше, зато число значит то, что написано.
    *[f"/edu/b/{n}" for n in range(1, 16)],
    "/login",
    "/register",
    "/survey",
    "/ro/",
    "/ro/brokers",
]

# Порог «страница не отрисовалась». Считается по длине видимого текста, а не
# по числу элементов: /login честно состоит из 12 подписей, и по элементам он
# попадал в тот же список, что и упавшая глава. Текста же на нём 150 знаков
# против нуля у главы — разница, которую видно.
МИНИМУМ_ТЕКСТА = 60

ЗАМЕР = r"""() => {
  // ── цвет ──────────────────────────────────────────────────────────────
  function разбор(с) {
    const m = String(с).match(/rgba?\(([^)]+)\)/);
    if (!m) return null;
    const ч = m[1].split(',').map(x => parseFloat(x.trim()));
    return { r: ч[0], g: ч[1], b: ч[2], a: ч.length > 3 ? ч[3] : 1 };
  }
  function поверх(верх, низ) {          // alpha-composite
    const a = верх.a + низ.a * (1 - верх.a);
    if (a === 0) return { r: 0, g: 0, b: 0, a: 0 };
    return {
      r: (верх.r * верх.a + низ.r * низ.a * (1 - верх.a)) / a,
      g: (верх.g * верх.a + низ.g * низ.a * (1 - верх.a)) / a,
      b: (верх.b * верх.a + низ.b * низ.a * (1 - верх.a)) / a,
      a: a,
    };
  }
  function яркость(ц) {
    const к = [ц.r, ц.g, ц.b].map(v => {
      v /= 255;
      return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * к[0] + 0.7152 * к[1] + 0.0722 * к[2];
  }
  function отношение(a, b) {
    const la = яркость(a), lb = яркость(b);
    return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
  }
  function hex(ц) {
    const h = v => Math.round(v).toString(16).padStart(2, '0');
    return '#' + h(ц.r) + h(ц.g) + h(ц.b);
  }

  // 🔴 Фон ищется, а не назначается: ровно здесь ошибся аудит 03.09.
  // Возвращает null, если дошли до верха, так и не встретив непрозрачного
  // фона, ИЛИ если по пути попалась фоновая картинка — цвет фона в этом
  // случае неизвестен, и число было бы выдумкой.
  function фонПод(эл) {
    let слои = [], у = эл;
    while (у) {
      const s = getComputedStyle(у);
      if (s.backgroundImage && s.backgroundImage !== 'none') return { картинка: true };
      const ц = разбор(s.backgroundColor);
      if (ц && ц.a > 0) {
        слои.push(ц);
        if (ц.a === 1) break;
      }
      у = у.parentElement;
    }
    if (!слои.length || слои[слои.length - 1].a !== 1) return null;
    let итог = слои.pop();
    while (слои.length) итог = поверх(слои.pop(), итог);
    return { цвет: итог };
  }

  const плохие = [], пары = {};
  let пропущено = 0, проверено = 0;

  for (const эл of document.querySelectorAll('body *')) {
    // Только элементы с собственным текстом: иначе один и тот же текст
    // посчитался бы на каждом предке.
    let свой = '';
    for (const у of эл.childNodes)
      if (у.nodeType === 3) свой += у.textContent;
    свой = свой.trim().replace(/\s+/g, ' ');
    if (!свой) continue;

    const s = getComputedStyle(эл);
    if (s.display === 'none' || s.visibility === 'hidden' || +s.opacity === 0) continue;
    const п = эл.getBoundingClientRect();
    if (п.width < 1 || п.height < 1) continue;

    // 🔴 Выключенные элементы управления. WCAG 1.4.3 прямо выводит их
    // из-под требования («incidental text»), и правильно: серый цвет и
    // ЕСТЬ сообщение «нажать нельзя». Без этой проверки замер поставил
    // выключенной кнопке «Проверить →» 1.19:1 и вывел её в худшие находки
    // по сайту — притом что чинить там нечего.
    if (эл.disabled || эл.closest('[disabled], [aria-disabled="true"], fieldset[disabled]')) continue;
    // aria-hidden скрыт от чтения с экрана — как и у axe, не считаем.
    if (эл.closest('[aria-hidden="true"]')) continue;

    // 🔴 В SVG текст красится fill, а не color. color у <text> остаётся
    // унаследованным от страницы, и первый прогон сравнил тёмный
    // унаследованный color с тёмным фоном графика: 26 подписей уровней
    // получили 1.00:1 и возглавили список «нечитаемого». На деле fill там
    // #c0392b. Худшая находка замера оказалась багом самого замера.
    const вSVG = !!эл.ownerSVGElement;
    const текст = разбор(вSVG ? s.fill : s.color);
    if (!текст || текст.a === 0) continue;
    if (вSVG && (s.fill === 'none' || /url\(/.test(s.fill))) continue;

    const фон = фонПод(эл);
    if (!фон || фон.картинка) { пропущено++; continue; }

    const цт = текст.a < 1 ? поверх(текст, фон.цвет) : текст;
    const размер = parseFloat(s.fontSize);
    const жирный = (parseInt(s.fontWeight, 10) || 400) >= 700;
    const крупный = размер >= 24 || (жирный && размер >= 18.66);
    const порог = крупный ? 3.0 : 4.5;

    проверено++;
    const к = отношение(цт, фон.цвет);
    if (к >= порог) continue;

    const ключ = hex(цт) + ' на ' + hex(фон.цвет);
    if (!пары[ключ]) пары[ключ] = { n: 0, k: Math.round(к * 100) / 100, пример: свой.slice(0, 60) };
    пары[ключ].n++;
    if (плохие.length < 400)
      плохие.push({
        тег: эл.tagName.toLowerCase(),
        класс: (эл.className && эл.className.baseVal !== undefined
                ? эл.className.baseVal : String(эл.className || '')).slice(0, 60),
        цвет: hex(цт), фон: hex(фон.цвет),
        k: Math.round(к * 100) / 100, порог: порог,
        размер: размер, текст: свой.slice(0, 50),
      });
  }
  return { плохие, пары, пропущено, проверено,
           текста: (document.body.innerText || '').trim().length };
}"""


def прогон(стр, путь: str, ширина: int, база: str = БАЗА) -> dict:
    стр.set_viewport_size({"width": ширина, "height": 900})
    стр.goto(база + путь, wait_until="domcontentloaded", timeout=45000)
    стр.wait_for_timeout(2500)
    # Ленивые блоки ниже сгиба: без прокрутки половина страницы не
    # отрисована, и замер покажет благополучие там, где его нет.
    стр.evaluate("() => window.scrollTo(0, document.body.scrollHeight)")
    стр.wait_for_timeout(1200)
    стр.evaluate("() => window.scrollTo(0, 0)")
    стр.wait_for_timeout(400)
    return стр.evaluate(ЗАМЕР)


def прогон_с_ошибками(стр, путь: str, ширина: int, база: str) -> dict:
    """То же, но с уловленными pageerror.

    🔴 Замер «сколько плохого» на упавшей странице всегда идеален: главу 5
    я уронил своим же aria-label, и щуп отрапортовал «0 контролов без
    имени» — потому что контролов не осталось. Ошибки страницы собираются
    в тот же результат, чтобы ноль никогда не проходил молча.
    """
    ошибки: list[str] = []
    приёмник = lambda e: ошибки.append(str(e)[:160])  # noqa: E731
    стр.on("pageerror", приёмник)
    try:
        итог = прогон(стр, путь, ширина, база)
    finally:
        стр.remove_listener("pageerror", приёмник)
    итог["ошибки_страницы"] = ошибки
    return итог


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--url", action="append", help="конкретная страница")
    р.add_argument("--json", help="сохранить замер в файл")
    р.add_argument("--diff", help="сравнить с сохранённым замером")
    р.add_argument("--подробно", action="store_true")
    р.add_argument("--база", default=БАЗА,
                   help="адрес сервера; для платных глав — стенд edu_preview.py")
    р.add_argument("--токен",
                   help="сессия из edu_preview.py: кладётся в localStorage "
                        "ключом sbf_token ДО перехода, иначе отдаётся пейволл")
    а = р.parse_args()

    страницы = а.url or СТРАНИЦЫ
    итог: dict[str, dict] = {}
    пусто: list[str] = []
    сломано: list[str] = []

    with sync_playwright() as pw:
        бр = pw.chromium.launch()
        ctx = бр.new_context()
        if а.токен:
            # 🔴 Кука обязательна, localStorage одного мало. Гейт платных
            # глав живёт на СЕРВЕРЕ (_handle_edu → is_pro), а обычная
            # навигация не может приложить заголовок — serve.py читает
            # куку sbf_session. Токен только в localStorage дал бы 200 и
            # заглушку пейволла: страница открылась, мерить нечего.
            ctx.add_cookies([{"name": "sbf_session", "value": а.токен,
                              "url": а.база}])
            # А это — для клиентского кода главы (fetch прогресса и т.п.),
            # add_init_script, а не evaluate после goto: страница читает
            # токен при загрузке, выставленный позже он уже не поможет.
            ctx.add_init_script(
                f"try {{ localStorage.setItem('sbf_token', {json.dumps(а.токен)}); }}"
                " catch (e) {}")
        стр = ctx.new_page()
        for путь in страницы:
            строка = {}
            for имя, ширина in (("desktop", 1366), ("mobile", 390)):
                try:
                    строка[имя] = прогон_с_ошибками(стр, путь, ширина, а.база)
                except Exception as e:  # страница может не открыться — это тоже результат
                    строка[имя] = {"ошибка": str(e)[:200]}
            итог[путь] = строка
            d = строка.get("desktop", {})
            m = строка.get("mobile", {})
            if "ошибка" in d:
                print(f"{путь:28} ✗ {d['ошибка'][:70]}")
                continue
            метка = ""
            if d.get("текста", 0) < МИНИМУМ_ТЕКСТА:
                метка = f"  ⚠ видимого текста {d.get('текста', 0)} знаков — страница не отрисовалась"
                пусто.append(путь)
            print(f"{путь:22} desktop {len(d['плохие']):4}  mobile {len(m.get('плохие', [])):4}"
                  f"   текста {d.get('текста', 0):6}  (на картинках: {d['пропущено']}){метка}")
        бр.close()

    # ── сводка по парам цветов: что чинить, а не где ────────────────────
    пары: dict[str, dict] = {}
    for строка in итог.values():
        for вид in строка.values():
            for ключ, знач in (вид.get("пары") or {}).items():
                п = пары.setdefault(ключ, {"n": 0, "k": знач["k"], "пример": знач["пример"]})
                п["n"] += знач["n"]

    print("\nПары цветов по убыванию частоты:")
    for ключ, з in sorted(пары.items(), key=lambda x: -x[1]["n"])[:15]:
        print(f"  {з['n']:5}×  {ключ:26} {з['k']:5.2f}:1   «{з['пример']}»")

    всего = sum(len(в.get("плохие", [])) for с in итог.values() for в in с.values())
    print(f"\nВсего элементов ниже AA: {всего}")
    if пусто:
        print(f"⚠ НЕ ЗАСЧИТЫВАТЬ как «чисто»: {', '.join(пусто)} — там нечего было мерить.")

    if а.json:
        Path(а.json).write_text(json.dumps(итог, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"замер сохранён: {а.json}")

    if а.diff:
        было = json.loads(Path(а.diff).read_text(encoding="utf-8"))
        print(f"\nСравнение с {а.diff}:")
        for путь, строка in итог.items():
            for вид, данные in строка.items():
                стало = len(данные.get("плохие", []))
                б = len((было.get(путь, {}).get(вид, {}) or {}).get("плохие", []))
                знак = "=" if б == стало else ("↓" if стало < б else "↑")
                print(f"  {путь:22} {вид:8} {б:4} → {стало:4}  {знак}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
