# -*- coding: utf-8 -*-
"""tools/make_logo.py — знак SBF для шапки сайта, без подложки.

🔴 ЗАЧЕМ. `logo-master.png` нарисован НА БЕЛОМ КВАДРАТЕ: альфа есть, но
она сплошная, 100% непрозрачных пикселей. На десктопе этого не видно —
шапка сама светлая, плашка сливается. На телефоне фон шапки другой, и
белый квадрат вылезает прямоугольником вокруг знака. Жалоба владельца
09.10.2026 звучала ровно так: «на ПК не видно, на телефоне видно».

🔴 ПОЧЕМУ ЗАЛИВКА ОТ КРАЁВ, А НЕ «ВСЕ БЕЛЫЕ ПИКСЕЛИ ПРОЗРАЧНЫЕ».
Внутри знака 426 тысяч почти белых пикселей — это блики на золоте.
Снести их по цвету значит продырявить сам логотип, причём заметно это
станет только на тёмном фоне, то есть не сразу. Поэтому удаляется
только тот белый, что СВЯЗАН с краем картинки: подложка связана,
блики — нет.

Маска «почти белого» требует не только яркости, но и малого разброса
между каналами: кремовые блики знака тоже светлые, но у них красный
заметно выше синего, а подложка нейтральная.

Что НЕ трогаем: `web/assets/icons/icon-*.png`. Это иконки PWA с
`purpose: "any maskable"` — система обрезает их по своей форме и
подставляет свой фон; прозрачная maskable-иконка выглядит сломанной.
У них подложка обязана остаться.

Запуск:
    python3 tools/make_logo.py            # записать logo.png и logo-96.png
    python3 tools/make_logo.py --проверка # только показать, что получится
"""
from __future__ import annotations

import sys
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image

КОРЕНЬ = Path(__file__).resolve().parents[1]
ИСХОДНИК = КОРЕНЬ / "web/assets/logo-master.png"
ВЫХОД = {192: КОРЕНЬ / "web/assets/logo.png",
         96:  КОРЕНЬ / "web/assets/logo-96.png"}

ПОРОГ_ЯРКОСТИ = 234   # ниже — уже не подложка
ПОРОГ_РАЗБРОСА = 10   # разница между каналами: подложка нейтральна
ПОЛЕ = 0.06           # доля поля вокруг знака, чтобы он не лип к краю


def без_подложки(им: Image.Image) -> Image.Image:
    a = np.array(им.convert("RGBA")).astype(np.int16)
    h, w = a.shape[:2]
    rgb = a[:, :, :3]
    мин = rgb.min(axis=2)
    белое = (мин >= ПОРОГ_ЯРКОСТИ) & ((rgb.max(axis=2) - мин) <= ПОРОГ_РАЗБРОСА)

    фон = np.zeros((h, w), bool)
    оч: deque = deque()
    края = [(y, x) for x in range(w) for y in (0, h - 1)]
    края += [(y, x) for y in range(h) for x in (0, w - 1)]
    for y, x in края:
        if белое[y, x] and not фон[y, x]:
            фон[y, x] = True
            оч.append((y, x))
    while оч:
        y, x = оч.popleft()
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            ny, nx = y + dy, x + dx
            if 0 <= ny < h and 0 <= nx < w and белое[ny, nx] and not фон[ny, nx]:
                фон[ny, nx] = True
                оч.append((ny, nx))

    сохранено = int((белое & ~фон).sum())
    alpha = np.where(фон, 0, 255).astype(np.uint8)

    # Мягкая кромка: без неё по контуру знака остаётся белая обводка
    # в один-два пикселя — на тёмном фоне она читается как ореол.
    сосед = np.zeros((h, w), bool)
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        сдвиг = np.roll(np.roll(фон, dy, axis=0), dx, axis=1)
        сосед |= сдвиг
    кайма = сосед & ~фон
    доля = np.clip((ПОРОГ_ЯРКОСТИ - мин[кайма].astype(np.float32)) / 40.0, 0, 1)
    alpha[кайма] = (доля * 255).astype(np.uint8)

    a[:, :, 3] = alpha
    print(f"  подложка снята: {int(фон.sum()) * 100 // (h * w)}% площади; "
          f"светлых пикселей внутри знака сохранено {сохранено}")
    return Image.fromarray(a.astype(np.uint8))


def собрать() -> dict[int, Image.Image]:
    знак = без_подложки(Image.open(ИСХОДНИК))
    bbox = знак.getbbox()
    знак = знак.crop(bbox)
    print(f"  знак без полей: {знак.size[0]}×{знак.size[1]}")
    готово = {}
    for размер in ВЫХОД:
        поле = round(размер * ПОЛЕ)
        внутрь = размер - поле * 2
        k = min(внутрь / знак.size[0], внутрь / знак.size[1])
        нов = знак.resize((max(1, round(знак.size[0] * k)),
                           max(1, round(знак.size[1] * k))), Image.LANCZOS)
        холст = Image.new("RGBA", (размер, размер), (0, 0, 0, 0))
        холст.alpha_composite(нов, ((размер - нов.size[0]) // 2,
                                    (размер - нов.size[1]) // 2))
        готово[размер] = холст
    return готово


if __name__ == "__main__":
    образы = собрать()
    if "--проверка" in sys.argv:
        for размер, им in образы.items():
            непрозр = np.array(им)[:, :, 3]
            print(f"  {размер}×{размер}: прозрачных {int((непрозр == 0).sum()) * 100 // непрозр.size}%, "
                  f"угол {им.getpixel((0, 0))}")
        sys.exit(0)
    for размер, им in образы.items():
        им.save(ВЫХОД[размер], optimize=True)
        print(f"  ✓ {ВЫХОД[размер].relative_to(КОРЕНЬ)} — {размер}×{размер}, "
              f"угол {им.getpixel((0, 0))}, {ВЫХОД[размер].stat().st_size} байт")
