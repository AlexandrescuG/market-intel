#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""build_llms.py — llms.txt из тех же источников, что и сам сайт.

🔴 ЗАЧЕМ ГЕНЕРИРОВАТЬ, А НЕ ПИСАТЬ РУКАМИ. Прежний llms.txt от
20.06.2026 описывал компанию и не упоминал НИ ОДНОГО материала: ни
курса из пятнадцати глав, ни глоссария на 46 терминов, ни пяти
инструкций по площадкам. Языков там два, а сайт трёхъязычный с самого
начала. Файл, который правят отдельно от сайта, расходится с ним молча
— это ровно то, что случилось за три месяца.

🔴 ЧТО llms.txt ДАЁТ И ЧЕГО НЕ ДАЁТ. Поисковые ИИ-краулеры (GPTBot,
ClaudeBot, PerplexityBot) его игнорируют: цитаты берутся из самих
страниц. Читают его агентные инструменты — те, что работают со ссылкой
по запросу пользователя. Поэтому здесь не маркетинг, а карта: что на
сайте есть, по каким адресам и на каких языках.

Запуск:  python3 tools/build_llms.py
Выход:   web/llms.txt
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
from core import i18n  # noqa: E402

ДОМЕН = "https://lp.sbfconsult.com"


def _размер_карты() -> str:
    """«N адресов, M материалов × 3 языка» — СЧИТАЕТСЯ, а не вписывается.

    🔴 До 30.09.2026 строка была зашита как «84 адреса, 28 материалов».
    Числа перестали быть правдой в тот день, когда из карты убрали платные
    главы 6-15 и /register: адресов стало 51, материалов 17. Полгода
    llms.txt — файл, который существует ровно затем, чтобы ИИ-агент не
    гадал, — обещал агентам вдвое больше страниц, чем есть.

    Считаем по web/sitemap.xml, а не по маршрутам: карта и есть то, на что
    ссылается строка. Если файла нет, честнее не называть число вовсе, чем
    назвать вчерашнее.
    """
    карта = КОРЕНЬ / "web" / "sitemap.xml"
    try:
        адресов = карта.read_text(encoding="utf-8").count("<loc>")
    except OSError:
        return "собирается tools/build_sitemap.py"
    if not адресов:
        return "собирается tools/build_sitemap.py"
    языков = len(i18n.SUPPORTED_LANGS) if hasattr(i18n, "SUPPORTED_LANGS") else 3
    материалов, остаток = divmod(адресов, языков)
    if остаток:            # языки раскрыты не у всех страниц — не выдумываем
        return f"{_склонить(адресов, 'адрес', 'адреса', 'адресов')}"
    return (f"{_склонить(адресов, 'адрес', 'адреса', 'адресов')}, "
            f"{_склонить(материалов, 'материал', 'материала', 'материалов')} "
            f"× {_склонить(языков, 'язык', 'языка', 'языков')}")


def _склонить(n: int, один: str, два: str, много: str) -> str:
    """«51 адрес», а не «51 адресов». Файл читают агенты, но пишем мы для
    людей тоже, и кривая форма в нём выглядит как машинная халтура."""
    сотни = n % 100
    if 11 <= сотни <= 14:
        форма = много
    else:
        форма = {1: один, 2: два, 3: два, 4: два}.get(n % 10, много)
    return f"{n} {форма}"
ВЫХОД = КОРЕНЬ / "web" / "llms.txt"

# Постоянная часть: кто мы и чего НЕ делаем. Второе важнее первого —
# оно удерживает агента от обещаний, которых мы не даём.
ШАПКА = """# SBF Company — SBF Intelligence Terminal

> Сопровождение счёта, анализ рынка и подбор брокера для частных
> инвесторов. «SBF COMPANY» S.R.L., Кишинёв, Молдова (IDNO 1025600035871,
> LEI 254900BW4MI5M0006I30). Сайт компании — https://sbfconsult.com/,
> этот сайт — её терминал SBF Intelligence. Прежнее название бренда —
> SBF Consult. Сайт трёхъязычный: русский (/), румынский (/ro/),
> английский (/en/).

## Чего мы НЕ делаем

- Не продаём торговые сигналы
- Не гарантируем прибыль и не публикуем винрейты
- Не даём инвестиционных рекомендаций в юридическом смысле

## Что стоит знать о данных на сайте

- Спреды у площадок снимались нами вручную, у каждого числа есть дата
  снятия и указано, наш это замер или публикация брокера
- Юридические лица, юрисдикции и номера лицензий сверены по реестрам;
  там, где подтверждения не нашлось, это написано прямо
- Рейтингов и отзывов о брокерах у нас нет: они не собраны, и мы их
  не выдумываем
"""


def главы() -> list[str]:
    строки = []
    for n in range(1, 16):
        назв = i18n.t(f"eduindex.chapters.{n}.title", "ru")
        под = i18n.t(f"eduindex.chapters.{n}.sub", "ru")
        строки.append(f"- [Глава {n}. {назв}]({ДОМЕН}/edu/b/{n}): {под}")
    return строки


def брокеры() -> list[str]:
    п = КОРЕНЬ / "web" / "data" / "partners.json"
    данные = json.loads(п.read_text("utf-8"))
    строки = []
    for б in данные.get("partners", []):
        if not б.get("enabled"):
            continue
        юр = [e.get("legal_name") for e in б.get("entities") or [] if e.get("legal_name")]
        хвост = f" Юрлица: {', '.join(юр)}." if юр else ""
        строки.append(f"- [{б['name']}]({ДОМЕН}/brokers/{б['id']}): "
                      f"регистрация, пополнение, верификация и торговля "
                      f"по шагам со скриншотами.{хвост}")
    return строки


def термины() -> tuple[int, list[str]]:
    п = КОРЕНЬ / "web" / "assets" / "glossary.json"
    словарь = json.loads(п.read_text("utf-8"))
    # Не перечисляем все 46: llms.txt — карта, а не копия глоссария.
    # Даём адрес с якорем на примере, чтобы схема ссылки была понятна.
    примеры = ", ".join(т["term"] for т in словарь[:8] if т.get("term"))
    return len(словарь), [
        f"- [Глоссарий]({ДОМЕН}/glossary): {len(словарь)} терминов "
        f"с определениями. У каждого свой якорь: {ДОМЕН}/glossary#gl-<slug>. "
        f"Например: {примеры}."
    ]


def собрать() -> str:
    всего, глос = термины()
    части = [ШАПКА, "## Разделы\n"]
    части += [
        f"- [Сегодня]({ДОМЕН}/): обзор рынка, обсуждаемость активов "
        f"по упоминаниям в новостях, Telegram и X, календарь ближайших событий.",
        f"- [Графики]({ДОМЕН}/chart.html): свечи, уровни и привязанные "
        f"к инструменту новости.",
        f"- [Экономический календарь]({ДОМЕН}/calendar): публикации "
        f"статистики с прогнозом, фактом и предыдущим значением.",
        f"- [Сравнение брокеров]({ДОМЕН}/brokers): юрлица, лицензии, "
        f"минимальный депозит, комиссии и спреды пяти площадок.",
        *глос,
        f"- [Курс «Биржевая торговля»]({ДОМЕН}/edu/): 15 глав. "
        f"Главы 1–5 открыты, 6–15 требуют аккаунта.",
        "",
        "## Инструкции по площадкам\n",
        *брокеры(),
        "",
        "## Главы курса\n",
        *главы(),
        "",
        "## Машиночитаемое\n",
        f"- Карта сайта: {ДОМЕН}/sitemap.xml ({_размер_карты()})",
        f"- robots.txt: {ДОМЕН}/robots.txt (доступ ИИ-краулерам открыт явно)",
        "- На каждой странице: canonical, hreflang на три языка и разметка",
        "  schema.org (Course, LearningResource, DefinedTermSet, HowTo,",
        "  BreadcrumbList). Текст страниц отдаётся сервером и читается",
        "  без исполнения JavaScript.",
        "",
        f"Обновлено: {date.today().isoformat()}",
    ]
    return "\n".join(части) + "\n"


def main() -> int:
    текст = собрать()
    ВЫХОД.write_text(текст, encoding="utf-8")
    print(f"записано: {ВЫХОД.relative_to(КОРЕНЬ)} "
          f"({len(текст)} знаков, {текст.count(chr(10)) + 1} строк)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
