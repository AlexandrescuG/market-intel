"""core/symbol_alias.py — одно имя на один актив.

ЗАЧЕМ. В Эпицентре рядом стояли «#NVIDIA — 8 за час · ×4.2» и «NVDA — 7 за
час · нормы пока нет». Это одна компания, посчитанная дважды.

ОТКУДА ВЗЯЛИСЬ ДВА ИМЕНИ. Упоминания приходят из двух мест, и каждое называет
актив по-своему:

  news_instrument_tags — разметка по словарю выражений. Ключи оттуда взяты из
                         каталога брокера: «#NVIDIA», «US_500», «ETHUSD».
  signals.cashtags     — кештеги из постов X и Telegram: «$NVDA» → «NVDA».

Обе величины складывались одним `_merge`, но складывать было нечего: ключи
разные, и вместо суммы получались две строки на доске. Хуже того, младшая из
двух не имела истории — а значит и нормы, — и попадала наверх с множителем,
посчитанным от пола 0.5. Так «NVDA, которого никто не упоминал» обгонял
«#NVIDIA, о котором вышло 146 новостей за сутки».

🔴 КАРТА НЕ ПИШЕТСЯ РУКАМИ. Она уже есть в каталоге брокера, двумя полями:

    {"symbol": "#NVIDIA", "name": "NVDA",     "canonical": null}
    {"symbol": "US_500",  "name": "S&P 500",  "canonical": "SPX"}
    {"symbol": "ETHUSD",  "name": "Эфириум",  "canonical": "ETH"}

Правило одно: **каноническое имя — это `canonical`, если он задан, иначе
`symbol`**. У акций `canonical` пуст, зато в `name` лежит биржевой тикер — он
и становится псевдонимом. Для индексов и криптовалют наоборот: `canonical`
задан, и к нему сводится длинное брокерское имя.

🔴 ПСЕВДОНИМ НЕ ПЕРЕБИВАЕТ НАСТОЯЩИЙ СИМВОЛ. Если тикер одного инструмента
совпал с символом другого, псевдоним отбрасывается: путаница двух разных
активов хуже, чем два имени у одного.
"""
from __future__ import annotations

import json
import logging
import re
from pathlib import Path

log = logging.getLogger("symbol_alias")

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "web" / "data" / "broker_catalog.json"

# Тикер — только заглавные латинские буквы и точка: «NVDA», «BRK.B».
# «S&P 500» и «Эфириум» под это не подходят и псевдонимами не становятся.
_ТИКЕР = re.compile(r"^[A-Z][A-Z.]{0,6}$")

_карта: dict[str, str] | None = None


def _построить() -> dict[str, str]:
    try:
        raw = json.loads(CATALOG.read_text(encoding="utf-8"))
    except Exception as e:
        log.warning("каталог не прочитан, псевдонимы не работают: %s", str(e)[:120])
        return {}
    items = raw.get("items", raw) if isinstance(raw, dict) else raw

    настоящие = {it.get("symbol") for it in items if it.get("symbol")}
    карта: dict[str, str] = {}
    спорные: set[str] = set()

    for it in items:
        символ = it.get("symbol")
        if not символ:
            continue
        канон = it.get("canonical") or символ
        if канон != символ:
            карта[символ] = канон

        тикер = (it.get("name") or "").strip()
        if not тикер or тикер == символ or not _ТИКЕР.match(тикер):
            continue
        # Тикер, который сам является символом другого инструмента, —
        # не псевдоним. Пример формы: «ED» как тикер #EDISON и «ED» как
        # отдельная позиция каталога.
        if тикер in настоящие:
            continue
        if тикер in карта and карта[тикер] != канон:
            спорные.add(тикер)
            continue
        карта[тикер] = канон

    # Один тикер на два инструмента — не сводим ни к одному из них.
    for т in спорные:
        карта.pop(т, None)
    if спорные:
        log.info("тикеров с двумя владельцами, оставлены как есть: %d", len(спорные))
    return карта


def карта() -> dict[str, str]:
    global _карта
    if _карта is None:
        _карта = _построить()
    return _карта


def canon(symbol: str) -> str:
    """Каноническое имя актива. Незнакомое имя возвращается как есть."""
    return карта().get(symbol, symbol)


def names_for(symbol: str) -> list[str]:
    """Все имена, под которыми этот актив мог быть записан.

    Нужно на выдаче: человек нажимает «#NVIDIA», а часть упоминаний лежит в
    базе под «NVDA» — их надо собрать вместе, иначе половина ленты пропадёт.
    """
    цель = canon(symbol)
    имена = {symbol, цель}
    имена |= {имя for имя, к in карта().items() if к == цель}
    return sorted(имена)


def reload() -> int:
    """Перечитать каталог (он обновляется мостом раз в сутки)."""
    global _карта
    _карта = _построить()
    return len(_карта)
