"""Короткая запись в SQLite, которая не падает от чужой блокировки.

🔴 ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ТРИ КОПИИ НА МЕСТАХ.

За один день 14.09.2026 «database is locked» нашёлся в трёх фоновых
задачах — pulse_job, sr_levels_job, news_geo_job. Форма у всех одна:
сначала долгое чтение, потом цикл записи, и единственный commit() в
конце. Это не три бага, а один, размноженный копированием, — поэтому и
лечение живёт в одном месте.

ПОЧЕМУ НЕ ХВАТАЕТ busy_timeout. У pulse_job он стоял равным 60 секундам,
щуп показал занятость записи 22% времени с максимумом 33 секунды подряд —
ожидания хватало с запасом, и юнит всё равно падал в 88 прогонах из 126.
Ожидание применяется не ко всякому отказу: пока соединение держит снимок
для чтения, а база под ним ушла вперёд, попытка писать получает
SQLITE_BUSY_SNAPSHOT — отказ по невозможности, а не по занятости. SQLite
его не повторяет вовсе, сколько таймаут ни ставь. В логе он неотличим от
обычной занятости: текст один и тот же.

ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ. Явный BEGIN IMMEDIATE берёт запись сразу, без
стадии чтения, поэтому снимка, который мог устареть, попросту нет. Всё
остальное — посчитать данные ДО вызова и отдать их одним куском, чтобы
блокировка держалась доли секунды, а не весь прогон.

Проверять ветку повторов надо контролем с известным ответом: при короткой
блокировке её съедает само ожидание, и она останется мёртвым кодом.
Держим запись дольше busy_timeout — тогда в логе видно «попытка 1 …
удалась с попытки 2».
"""
from __future__ import annotations

import sqlite3
import time
from typing import Callable

ПОПЫТОК = 6
ПЕРВАЯ_ПАУЗА = 0.5


def записать(con: sqlite3.Connection, пишем: Callable[[sqlite3.Connection], None],
             попыток: int = ПОПЫТОК, verbose: bool = False) -> int:
    """Выполнить `пишем(con)` в одной короткой транзакции. Вернуть номер удачной попытки.

    `пишем` обязана только писать: любое чтение внутри удлиняет блокировку,
    а ради её краткости всё и затевалось. Повторный вызов должен быть
    безопасен — при отказе транзакция откатывается и `пишем` зовётся снова.
    """
    задержка = ПЕРВАЯ_ПАУЗА
    for попытка in range(1, попыток + 1):
        try:
            con.execute("BEGIN IMMEDIATE")
            пишем(con)
            con.commit()
            if verbose and попытка > 1:
                print(f"  запись удалась с попытки {попытка}")
            return попытка
        except sqlite3.OperationalError as e:
            try:
                con.rollback()
            except sqlite3.Error:
                pass
            if попытка == попыток:
                raise
            if verbose:
                print(f"  попытка {попытка}: {e}; жду {задержка:.1f} с")
            time.sleep(задержка)
            задержка *= 2
    raise AssertionError("недостижимо")
