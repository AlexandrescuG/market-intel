"""Часы входа против часов заработка — статистика для главы 10.

🔴 ЧТО ИМЕННО ОБЕЩАНО. Глава 5 говорит читателю дословно: «через тридцать
сделок дневник покажет, в какие часы ты входишь и в какие зарабатываешь —
очень часто это разные часы». Глава 10 — то место, где обещание должно
исполниться. Значит считать надо ровно две вещи и рядом: РАСПРЕДЕЛЕНИЕ
ВХОДОВ по часам и РАСПРЕДЕЛЕНИЕ РЕЗУЛЬТАТА по тем же часам. Одна метрика
без второй превращает обещание в общие слова: «в 14:00 у тебя 30 сделок» не
говорит ничего, пока рядом не стоит, сколько они принесли.

ЧАС СЧИТАЕТСЯ ПО ВХОДУ, А НЕ ПО ВЫХОДУ. Вопрос читателя — «когда мне
садиться за терминал», а садится он в момент входа. Час закрытия
интересен отдельно и здесь не считается, чтобы две разные вещи не
смешались в одной таблице.

🔴 РЕЗУЛЬТАТ СУММИРУЕМ В R, А НЕ В ДЕНЬГАХ. Размер позиции у одного и того
же человека меняется в разы, и сумма в валюте скажет больше о размере
ставки, чем о часе. pnl_r уже посчитан при записи сделки (отношение к
риску), и он сравним между сделками.

ПОРОГИ — ИЗ СПЕКИ, И ОНИ НЕ ФОРМАЛЬНОСТЬ. Меньше 20 сделок у человека —
показывать нечего: в сутках 24 часа, и два десятка сделок размажутся по
ним так, что любой «лучший час» окажется случайностью. Ровно поэтому
ниже считается и число часов, где сделок хватает на разговор.
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

_DB = Path(__file__).parent.parent / "data" / "journal.db"

МИН_СДЕЛОК_ЧЕЛОВЕКА = 20       # ниже этого персональная разбивка бессмысленна
МИН_СДЕЛОК_В_ЧАСЕ = 3          # час с одной сделкой — не наблюдение
МИН_ПОЛЬЗОВАТЕЛЕЙ_ПЛАТФОРМЫ = 50
МИН_СДЕЛОК_ПЛАТФОРМЫ = 1000


def _conn(путь: str | Path | None = None) -> sqlite3.Connection:
    c = sqlite3.connect(str(путь or _DB), timeout=20)
    c.execute("PRAGMA busy_timeout=20000")
    c.row_factory = sqlite3.Row
    return c


def _по_часам(строки: list[sqlite3.Row]) -> list[dict]:
    """Свод по часу входа: сколько сделок и сколько R они принесли."""
    ведро: dict[int, dict] = {}
    for r in строки:
        ч = r["hour"]
        if ч is None:
            continue
        b = ведро.setdefault(int(ч), {"час": int(ч), "сделок": 0,
                                      "сумма_r": 0.0, "плюсовых": 0})
        b["сделок"] += 1
        b["сумма_r"] += float(r["pnl_r"] or 0)
        if float(r["pnl_r"] or 0) > 0:
            b["плюсовых"] += 1
    вышло = []
    for b in sorted(ведро.values(), key=lambda x: x["час"]):
        b["сумма_r"] = round(b["сумма_r"], 2)
        b["средний_r"] = round(b["сумма_r"] / b["сделок"], 3)
        b["доля_плюсовых"] = round(b["плюсовых"] / b["сделок"], 2)
        # Час, где сделок мало, отдаём вместе со всеми, но помечаем: прятать
        # его нельзя (иначе картина будет слишком гладкой), а делать по нему
        # выводы — тоже.
        b["мало_данных"] = b["сделок"] < МИН_СДЕЛОК_В_ЧАСЕ
        вышло.append(b)
    return вышло


def _разбор(часы: list[dict]) -> dict:
    """Где чаще всего входят и где на самом деле зарабатывают."""
    годные = [ч for ч in часы if not ч["мало_данных"]]
    if not годные:
        return {"час_входов": None, "час_заработка": None, "совпадают": None}
    самый_частый = max(годные, key=lambda ч: ч["сделок"])
    самый_прибыльный = max(годные, key=lambda ч: ч["сумма_r"])
    return {
        "час_входов": самый_частый["час"],
        "сделок_в_нём": самый_частый["сделок"],
        "r_в_нём": самый_частый["сумма_r"],
        "час_заработка": самый_прибыльный["час"],
        "r_в_лучшем": самый_прибыльный["сумма_r"],
        "сделок_в_лучшем": самый_прибыльный["сделок"],
        # То самое «очень часто это разные часы» из обещания. Отвечаем
        # фактом, а не пересказом обещания.
        "совпадают": самый_частый["час"] == самый_прибыльный["час"],
    }


def свои_часы(user_id: str = "default", путь=None) -> dict:
    """Персональная разбивка. Ниже порога честно говорит, чего не хватает."""
    c = _conn(путь)
    try:
        строки = c.execute(
            """SELECT CAST(strftime('%H', t.open_ts) AS INTEGER) AS hour,
                      t.pnl_r
               FROM trades t WHERE t.user_id = ?""", (user_id,)).fetchall()
    finally:
        c.close()
    всего = len(строки)
    if всего < МИН_СДЕЛОК_ЧЕЛОВЕКА:
        return {"available": False, "trade_count": всего,
                "нужно_сделок": МИН_СДЕЛОК_ЧЕЛОВЕКА,
                "why": "сделок в журнале меньше порога"}
    часы = _по_часам(строки)
    return {"available": True, "trade_count": всего,
            "часы": часы, **_разбор(часы)}


def часы_платформы(путь=None) -> dict:
    """Та же разбивка по всем пользователям — фон, с которым сравнивают себя.

    🔴 Никаких имён и никакой привязки к людям: наружу уходят только
    агрегаты и число участников. Сравнение «ты против всех» не стоит того,
    чтобы из него можно было вычислить чей-то журнал.
    """
    c = _conn(путь)
    try:
        всего = c.execute("SELECT COUNT(*) FROM trades").fetchone()[0]
        людей = c.execute(
            "SELECT COUNT(DISTINCT user_id) FROM trades").fetchone()[0]
        строки = c.execute(
            """SELECT CAST(strftime('%H', open_ts) AS INTEGER) AS hour, pnl_r
               FROM trades""").fetchall()
    finally:
        c.close()
    if людей < МИН_ПОЛЬЗОВАТЕЛЕЙ_ПЛАТФОРМЫ or всего < МИН_СДЕЛОК_ПЛАТФОРМЫ:
        return {"available": False, "n_users": людей, "n_trades": всего,
                "нужно_пользователей": МИН_ПОЛЬЗОВАТЕЛЕЙ_ПЛАТФОРМЫ,
                "нужно_сделок": МИН_СДЕЛОК_ПЛАТФОРМЫ,
                "why": "на платформе пока мало данных для сравнения"}
    часы = _по_часам(строки)
    return {"available": True, "n_users": людей, "n_trades": всего,
            "часы": часы, **_разбор(часы)}
